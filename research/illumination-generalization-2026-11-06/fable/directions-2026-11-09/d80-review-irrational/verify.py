"""d80: referee checks for qclass-closure/bbbb/high-valency-geometry.md (equal-rates branch).

Reads cell sets of four saved rooms only (cov3397, cov3608, cov4474 from d79; st279).
Reuses d79's edge-involution and corner-permutation code. No search over rooms, rays,
directions or reflection words.

For each room it checks, at the level of sheet monodromy on cells:
  * every invariant block system, the genus of each quotient N, and Riemann-Hurwitz for
    phi: Q -> N, split into simple (e=2) and reflex (e=3) ramification, real vs nonreal;
  * for every pair of distinct interior unit grid edges of the same axis whose lines have
    the same parity (the configuration forced by equal rates), the orbital union U
    generated by the K_{2,2} of incident cells and its transposes: its valency d, the
    coincidence budget 2d = R + J, whether d <= r, and the minimal block of the 4 cells.
Run: python3 -B verify.py > verify.log
"""
import sys
import time
from itertools import product
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'd72-cylinder-test'))
sys.argv = [sys.argv[0]]
src = (HERE.parent / 'd79-review-eight-sheet' / 'verify.py').read_text().replace('\nmain()\n', '\n')
d79 = type(sys)('d79v')
d79.__file__ = str(HERE.parent / 'd79-review-eight-sheet' / 'verify.py')
exec(compile(src, d79.__file__, 'exec'), d79.__dict__)
import cyl  # noqa: E402

TARGETS = ('cov3397', 'cov3608', 'cov4474', 'st279')


def cycles(g):
    seen, out = set(), []
    for i in range(len(g)):
        if i in seen:
            continue
        c, j = [], i
        while j not in seen:
            seen.add(j)
            c.append(j)
            j = g[j]
        out.append(c)
    return out


def orbitals(gens, n):
    lab = {}
    k = 0
    for a in range(n):
        for b in range(n):
            if (a, b) in lab:
                continue
            todo = [(a, b)]
            lab[(a, b)] = k
            while todo:
                x, y = todo.pop()
                for g in gens:
                    p = (g[x], g[y])
                    if p not in lab:
                        lab[p] = k
                        todo.append(p)
            k += 1
    return lab


def class_corner(c, x):
    return next((c[0] + dx, c[1] + dy) for dx, dy in product((0, 1), repeat=2)
                if ((c[0] + dx) % 2, (c[1] + dy) % 2) == x)


def all_block_systems(gens, n):
    systems = set()
    for j in range(1, n):
        B = d79.min_block(gens, n, [0, j])
        if len(B) < n:
            systems.add(frozenset(frozenset(b) for b in d79.block_system(gens, n, B)))
    return systems


def analyse(name, cells):
    cells = set(map(tuple, cells))
    cl = sorted(cells)
    idx = {c: i for i, c in enumerate(cl)}
    n = len(cl)
    g = d79.corner_perms(cells, cl, idx)
    gens = list(g.values())
    refl = d79.walls_and_reflex(cells)
    r = len(refl)
    # local data: (pole x, cycle, lattice point, real?)
    loc = []
    for x, gx in g.items():
        for cyc in cycles(gx):
            p = class_corner(cl[cyc[0]], x)
            assert all(class_corner(cl[i], x) == p for i in cyc)
            inc = d79.incid(cells, p)
            loc.append((x, cyc, p, inc != 4))   # real = on the room boundary
    assert sorted(len(c) for _, c, _, _ in loc).count(3) == r
    print('== %s: n=%d r=%d reflex=%s' % (name, n, r, refl))

    # block systems and Riemann-Hurwitz for phi
    systems = all_block_systems(gens, n)
    print('  proper block systems (block sizes):', sorted(len(next(iter(s))) for s in systems))
    maxk = max((len(next(iter(s))) for s in systems), default=None)
    print('  maximal proper partitions:', sum(len(next(iter(s))) == maxk for s in systems) if systems else 0)
    for s in sorted(systems, key=lambda s: len(next(iter(s)))):
        k = len(next(iter(s)))
        m = n // k
        blk = {i: b for b in s for i in b}
        # genus of N over B: 2gN-2 = -2m + sum (m - #block cycles)
        ram_N = 0
        simple, simple_real, refl_ram, sum_e = 0, 0, 0, 0
        for x, gx in g.items():
            bl = sorted(s, key=min)
            bi = {b: t for t, b in enumerate(bl)}
            bperm = [bi[blk[gx[min(b)]]] for b in bl]
            ram_N += m - len(cycles(bperm))
        for x, cyc, p, real in loc:
            b = blk[cyc[0]]
            img_len = 1
            # length of the block cycle through blk(cyc[0]) under gx
            gx = g[x]
            cur = gx[cyc[0]]
            while blk[cur] != b:
                cur = gx[cur]
                img_len += 1
            e = len(cyc) // img_len
            sum_e += e - 1
            if e == 2:
                simple += 1
                simple_real += real
            if e == 3:
                refl_ram += 1
        gN = (-2 * m + ram_N + 2) // 2
        target = -2 - k * (2 * gN - 2)
        print('    k=%d m=%d genus(N)=%d  phi: simple=%d (real %d) reflex-ramified r0=%d  '
              'sum(e-1)=%d  RH target=%d' % (k, m, gN, simple, simple_real, refl_ram, sum_e, target))
        assert sum_e == -2 - k * (2 * gN - 2)

    lab = orbitals(gens, n)
    # local branch tables for the budget
    stats = {'pairs': 0, 'budget_ok': 0, 'd_le_r': 0, 'blocks': {}}
    low = []
    for axis in ('h', 'v'):
        if axis == 'h':   # interior horizontal unit edge at line y: cells (i,y-1),(i,y)
            edges = [((i, y), ((i, y - 1), (i, y))) for (i, y) in cl if (i, y - 1) in cells]
        else:
            edges = [((x, j), ((x - 1, j), (x, j))) for (x, j) in cl if (x - 1, j) in cells]
        for a in range(len(edges)):
            for b in range(a + 1, len(edges)):
                (pa, ca), (pb, cb) = edges[a], edges[b]
                line = 1 if axis == 'h' else 0
                if (pa[line] - pb[line]) % 2:
                    continue
                Sc, Tc = [idx[c] for c in ca], [idx[c] for c in cb]
                seeds = {lab[(s, t)] for s in Sc for t in Tc} | {lab[(t, s)] for s in Sc for t in Tc}
                U = {pq for pq, o in lab.items() if o in seeds}
                assert len(U) % n == 0
                d = len(U) // n
                R = sum(1 for x, cyc, p, real in loc if len(cyc) == 2 and (cyc[0], cyc[1]) in U)
                J = sum(1 for x, cyc, p, real in loc if len(cyc) == 3
                        for t in (1, 2) if (cyc[0], cyc[t]) in U)
                stats['pairs'] += 1
                stats['budget_ok'] += (2 * d == R + J)
                stats['d_le_r'] += (d <= r)
                kb = len(d79.min_block(gens, n, Sc + Tc))
                stats['blocks'][kb] = stats['blocks'].get(kb, 0) + 1
                if d <= r or kb < n:
                    low.append((axis, pa, pb, d, R, J, kb))
    print('  edge-mark pairs (same-parity lines): %d; budget 2d=R+J holds: %d; d<=r: %d' %
          (stats['pairs'], stats['budget_ok'], stats['d_le_r']))
    print('  minimal block of the 4 incident cells, size: count =', dict(sorted(stats['blocks'].items())))
    for rec in low[:12]:
        print('    proper-block or low-valency pair:', rec)
    if len(low) > 12:
        print('    ... %d more' % (len(low) - 12))


def main():
    t0 = time.process_time()
    rooms = dict(cyl.rooms())
    for name in TARGETS:
        analyse(name, rooms[name])
    print('CPU seconds: %.1f' % (time.process_time() - t0))


main()
