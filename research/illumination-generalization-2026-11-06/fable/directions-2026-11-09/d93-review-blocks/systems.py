"""d93: for a named room, list all G-block systems and each class's B_x, and whether each
proper system Sigma contains some proper B_x (i.e. Q/Sigma has no regular point over x)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
rid = sys.argv[1]
room = [r for r in json.load(open(os.path.join(HERE, '..', 'd8-perturbation-test', 'rooms.json'))) if r['id'] == rid][0]
cells = sorted(tuple(c) for c in room['cells']); idx = {c: i for i, c in enumerate(cells)}; n = len(cells)
def sig(ax, p):
    out = []
    for (i, j) in cells:
        d = -1 if (i, j)[ax] % 2 == p else 1
        nb = (i + d, j) if ax == 0 else (i, j + d)
        out.append(idx.get(nb, idx[(i, j)]))
    return out
S = {(ax, p): sig(ax, p) for ax in (0, 1) for p in (0, 1)}
g = {(p, q): [S[(0, p)][S[(1, q)][i]] for i in range(n)] for p in (0, 1) for q in (0, 1)}
gens = list(g.values())
def closure(pairs):
    lab = list(range(n))
    def f(a):
        while lab[a] != a: a = lab[a]
        return a
    def un(a, b):
        a, b = f(a), f(b)
        if a != b: lab[a] = b; return True
        return False
    for u, v in pairs: un(u, v)
    ch = True
    while ch:
        ch = False
        for gg in gens:
            for a in range(n):
                if un(gg[a], gg[f(a)]): ch = True
    parts = {}
    for a in range(n): parts.setdefault(f(a), []).append(a)
    return tuple(sorted(tuple(sorted(p)) for p in parts.values()))
def two(perm): return [(i, perm[i]) for i in range(n) if perm[i] > i and perm[perm[i]] == i]
# all block systems: joins of minimal ones; minimal blocks containing 0 from pairs suffice to list systems generated by one pair
syst = set()
frontier = {closure([(0, j)]) for j in range(1, n)}
while frontier:
    syst |= frontier
    new = set()
    for P in frontier:
        for j in range(1, n):
            Q = closure([(p[0], a) for p in P for a in p[1:]] + [(0, j)])
            if Q not in syst: new.add(Q)
    frontier = new
print(rid, 'n =', n, 'G-block systems (nblocks, size):', sorted((len(P), len(P[0])) for P in syst))
Bx = {k: closure(two(g[k])) for k in g}
for k in sorted(g): print('  B_x', k, 'nblocks', len(Bx[k]))
for P in sorted(syst, key=len):
    if 1 < len(P) < n:
        blk = {a: bi for bi, p in enumerate(P) for a in p}
        noreg = [k for k in g if all(blk[u] == blk[v] for u, v in two(g[k])) and two(g[k])]
        winv = all(len({blk[s[a]] for a in p}) == 1 for s in S.values() for p in P)
        print('  proper Sigma', len(P), 'x', len(P[0]), 'W-inv', winv, 'classes with no regular point in Q/Sigma:', noreg)
