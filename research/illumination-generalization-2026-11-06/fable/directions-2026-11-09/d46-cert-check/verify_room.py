"""d46: independent recheck of rooms, for validation and for any positive.

Two implementations, neither shares code with cert_check.c:
  I.  Own monodromy from edge involutions (as in ../d45-review-fstar/check_fstar.py):
      sigma_(a,b) = kv[a] o kh[b]; B_x = congruence generated by the 2-cycles of
      sigma_x, closed under all four sigmas; lifts of an interior class-A point are the
      two diagonal cell pairs around it; a lift pair is separated by B_x iff the lifts lie
      in different cycles of the sigma_A action on the blocks.
  II. roomtools (../d10-mechanisms): class_congruence, lifts, a_image, as in
      ../d43-review-d39/check_cross.py.
Also recomputes r, rho, corner classes and F* (../d44-cert-check-sizing/filter_rate.passes).

Input (stdin or file arg): one room per line "n x0 y0 x1 y1 ...".
Output: one line per room: n r classes rho fstar pairs positives(I) positives(II) blocks.
"""
import ast, sys, resource
from pathlib import Path
resource.setrlimit(resource.RLIMIT_CPU, (3600, 3600))
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'd10-mechanisms'))
import roomtools as rt  # noqa: E402

src = (HERE.parent / 'd44-cert-check-sizing' / 'filter_rate.py').read_text()
mod = ast.parse(src); mod.body = [b for b in mod.body if isinstance(b, ast.FunctionDef)]
FR = {}; exec(compile(mod, 'filter_rate_defs', 'exec'), FR)


def monodromy(cells):
    cl = sorted(cells); idx = {c: k for k, c in enumerate(cl)}
    def kap(axis, par):
        p = []
        for (i, j) in cl:
            v = (i, j)[axis]; lo = v if v % 2 == par else v + 1
            step = -1 if lo == v else 1
            nb = (i + step, j) if axis == 0 else (i, j + step)
            p.append(idx.get(nb, idx[(i, j)]))
        return p
    kv = {0: kap(0, 0), 1: kap(0, 1)}; kh = {0: kap(1, 0), 1: kap(1, 1)}
    sig = {(a, b): [kv[a][kh[b][k]] for k in range(len(cl))] for a in (0, 1) for b in (0, 1)}
    return cl, idx, sig


def congruence(n, gens, pairs):
    par = list(range(n))
    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    todo = list(pairs)
    while todo:
        a, b = todo.pop(); ra, rb = f(a), f(b)
        if ra == rb:
            continue
        par[ra] = rb
        for g in gens:
            todo.append((g[a], g[b]))
    return [f(x) for x in range(n)]


def two_cycles(p):
    return [(i, p[i]) for i in range(len(p)) if p[i] != i and p[p[i]] == i and i < p[i]]


def block_cycle_ids(lab, sa):
    """cycle id of each block under the action of sigma_A on blocks"""
    img = {}
    for k in range(len(lab)):
        img[lab[k]] = lab[sa[k]]
    cid = {}
    for b in img:
        if b in cid:
            continue
        x = b
        while x not in cid:
            cid[x] = b; x = img[x]
    return cid


def geometry(cells):
    pts = {(x + u, y + w) for (x, y) in cells for u in (0, 1) for w in (0, 1)}
    rho = [0] * 4; r = 0; cls = set(); interior = []
    for (x, y) in pts:
        k = sum((x - 1 + u, y - 1 + w) in cells for u in (0, 1) for w in (0, 1))
        if k in (1, 3):
            cls.add((x % 2, y % 2))
        if k == 3:
            r += 1; rho[(x % 2) * 2 + (y % 2)] += 1
        if k == 4:
            interior.append((x, y))
    return r, rho, cls, sorted(interior)


def method_I(cells, interior):
    cl, idx, sig = monodromy(cells)
    n = len(cl); gens = list(sig.values())
    out = {}; pos = set()
    for ox in (0, 1):
        for oy in (0, 1):
            marks = [p for p in interior if p[0] % 2 == ox and p[1] % 2 == oy]
            if len(marks) < 2:
                continue
            sa = sig[(ox, oy)]
            lifts = {}
            for (x, y) in marks:
                sw, se, nw, ne = idx[(x - 1, y - 1)], idx[(x, y - 1)], idx[(x - 1, y)], idx[(x, y)]
                assert sa[sw] == ne and sa[ne] == sw and sa[se] == nw and sa[nw] == se
                lifts[(x, y)] = (sw, se)
            ok = {(s, t) for i, s in enumerate(marks) for t in marks[i + 1:]}
            nbk = []
            for dx, dy in ((1, 0), (1, 1), (0, 1)):        # b, c, d
                sx = sig[(ox ^ dx, oy ^ dy)]
                lab = congruence(n, gens, two_cycles(sx))
                nbk.append(len(set(lab)))
                cid = block_cycle_ids(lab, sa)
                ok = {(s, t) for (s, t) in ok
                      if all(cid[lab[a]] != cid[lab[b]] for a in lifts[s] for b in lifts[t])}
            out[(ox, oy)] = nbk
            pos |= {((ox, oy), s, t) for (s, t) in ok}
    return out, pos


def method_II(cells, interior):
    out = {}; pos = set()
    for ox in (0, 1):
        for oy in (0, 1):
            marks = [p for p in interior if p[0] % 2 == ox and p[1] % 2 == oy]
            if len(marks) < 2:
                continue
            room, t = rt.room_tuple(cells, (ox, oy))
            L = {p: rt.lifts(room, t, p, (ox, oy)) for p in marks}
            ok = {(s, u) for i, s in enumerate(marks) for u in marks[i + 1:]}
            nbk = []
            for x in (1, 2, 3):
                B = rt.class_congruence(t, [x]); nbk.append(len(B))
                img = {}
                for s in marks:
                    img[s] = [rt.a_image(t, B, ls[0])[0] for ls in L[s]]
                ok = {(s, u) for (s, u) in ok if all(a != b for a in img[s] for b in img[u])}
            out[(ox, oy)] = nbk
            pos |= {((ox, oy), s, u) for (s, u) in ok}
    return out, pos


def verify(cells):
    r, rho, cls, interior = geometry(cells)
    n = len(cells)
    bI, pI = method_I(cells, interior)
    bII, pII = method_II(cells, interior)
    pairs = sum(len(v) * (len(v) - 1) // 2 for v in
                [[p for p in interior if p[0] % 2 == ox and p[1] % 2 == oy] for ox in (0, 1) for oy in (0, 1)])
    return dict(n=n, r=r, rho=rho, ncls=len(cls), fstar=bool(FR['passes'](rho, n, r)), pairs=pairs,
                posI=sorted(pI), posII=sorted(pII), blocksI=bI, blocksII=bII)


if __name__ == '__main__':
    fh = open(sys.argv[1]) if len(sys.argv) > 1 else sys.stdin
    for k, line in enumerate(fh, 1):
        v = list(map(int, line.split()))
        if not v:
            continue
        cells = set(zip(v[1::2], v[2::2])); assert len(cells) == v[0]
        res = verify(cells)
        bl = ' '.join('o(%d,%d) %s' % (o[0], o[1], res['blocksI'][o]) for o in sorted(res['blocksI']))
        agree = res['posI'] == res['posII'] and res['blocksI'] == res['blocksII']
        print('room %d n %d r %d corner_classes %d rho %s fstar %d pairs %d positives_I %d positives_II %d agree %d | %s'
              % (k, res['n'], res['r'], res['ncls'], ' '.join(map(str, res['rho'])), res['fstar'], res['pairs'],
                 len(res['posI']), len(res['posII']), agree, bl))
        for o, s, t in res['posI']:
            print('  POSITIVE_I origin_parity (%d,%d) S %s T %s' % (o[0], o[1], s, t))
        for o, s, t in res['posII']:
            print('  POSITIVE_II origin_parity (%d,%d) S %s T %s' % (o[0], o[1], s, t))
