def lit_all(P, S, T, maxrefl=60):
    Wl = walls(P)
    out = []
    for p, q in DIRS:
        r = walk(Wl, S, T, p, q, maxrefl)
        if r is not None:
            out.append(dict(dir=(p, q), refl=len(r[1]), con=r[1], tt=r[0]))
    return out


def single_pass(R, res, axis):
    """True if the path is one monotone pass of the chart on this axis, with at most one cap at each end."""
    con = res['con']
    if axis == 'y':
        rev = [pt[1] for pt, k in con if k == 'h']
        near, far = R.H, F(0)
    else:
        rev = [pt[0] for pt, k in con if k == 'v']
        near, far = F(0), R.W
    if len(rev) > 2:
        return False
    if len(rev) == 2:
        return rev == [near, far]
    return rev in ([], [near], [far])


def gate_x(R, S, res):
    """Physical transverse positions where the path crosses the y-gates y3, y2, y1 (y-chart)."""
    p, q = res['dir']
    X, Y = S
    vx, vy = p, q
    pts = [S] + [c[0] for c in res['con']]
    out = []
    for a, b in zip(pts, pts[1:] + [None]):
        if b is None:
            break
        for g in (R.y3, R.h + R.e, R.h):
            if (a[1] - g) * (b[1] - g) < 0:
                out.append((g, a[0] + (b[0] - a[0]) * (g - a[1]) / (b[1] - a[1])))
    return out


