DIRS = sorted({(p // gcd(p, q), q // gcd(p, q)) for p in range(-60, 61) for q in range(-60, 61)
               if p and q}, key=lambda d: (max(abs(d[0]), abs(d[1])), d))
DIRS = [(1, 0), (-1, 0), (0, 1), (0, -1)] + DIRS


def walls(P):
    n = len(P)
    P = [(F(a), F(b)) for a, b in P]
    vw = [(P[i][0], min(P[i][1], P[(i + 1) % n][1]), max(P[i][1], P[(i + 1) % n][1]))
          for i in range(n) if P[i][0] == P[(i + 1) % n][0]]
    hw = [(P[i][1], min(P[i][0], P[(i + 1) % n][0]), max(P[i][0], P[(i + 1) % n][0]))
          for i in range(n) if P[i][1] == P[(i + 1) % n][1]]
    return vw, hw, set(P)


def walk(Wl, S, T, p, q, maxrefl):
    """Follow direction (p,q) from S; return (travel parameter at T, contacts) if T is passed."""
    vw, hw, V = Wl
    X, Y = F(S[0]), F(S[1])
    vx, vy = p, q
    tt = F(0)
    con = []
    for _ in range(maxrefl + 1):
        best = None
        if vx:
            for a, lo, hi in vw:
                t = (a - X) / vx
                if t > 0 and (best is None or t < best[0]):
                    y = Y + vy * t
                    if lo <= y <= hi:
                        best = (t, 'v', a)
        if vy:
            for a, lo, hi in hw:
                t = (a - Y) / vy
                if t > 0 and (best is None or t < best[0]):
                    x = X + vx * t
                    if lo <= x <= hi:
                        best = (t, 'h', a)
        t = best[0]
        # does the open segment pass T?
        ts = (T[0] - X) / vx if vx else (T[1] - Y) / vy
        if 0 < ts < t and X + vx * ts == T[0] and Y + vy * ts == T[1]:
            return tt + ts, con
        X, Y = X + vx * t, Y + vy * t
        tt += t
        if (X, Y) in V:
            return None
        if _ == maxrefl:
            return None
        con.append(((X, Y), best[1]))
        if best[1] == 'v':
            vx = -vx
        else:
            vy = -vy
    return None


def lit_check(P, S, T, maxrefl=60):
    Wl = walls(P)
    S, T = (F(S[0]), F(S[1])), (F(T[0]), F(T[1]))
    for p, q in DIRS:
        r = walk(Wl, S, T, p, q, maxrefl)
        if r is not None:
            tt, con = r
            # independent replay with the verbatim tracer: segment length tt*(p,q) must end at T
            st, pos, con2 = trace(P, S, (S[0] + p * tt, S[1] + q * tt))
            ok = st == 'end' and pos == T and con2 == con
            return dict(dir=(p, q), refl=len(con), con=con, replay=ok)
    return None


def classify(R, S, T, res):
    """Describe the lighting path relative to both one-chart itineraries."""
    con = res['con']
    p, q = res['dir']
    kinds = ''.join(k for _, k in con)
    # original axis (longitudinal y): reversals are 'h' contacts; allowed: top cap y=H, floor y=0
    hy = [pt[1] for pt, k in con if k == 'h']
    hx = [pt[0] for pt, k in con if k == 'v']
    def axis_desc(rev, top, bot, name):
        inner = [r for r in rev if r not in (top, bot)]
        caps = [r for r in rev if r in (top, bot)]
        if not rev:
            return f'{name}: monotone, no cap'
        if inner:
            return f'{name}: turns back at inner step levels {sorted(set(inner))} ({len(rev)} reversals)'
        return f'{name}: monotone between caps {caps}'
    d1 = axis_desc(hy, R.H, F(0), 'y-chart')
    d2 = axis_desc(hx, F(0), R.W, 'x-chart')
    return f"dir {res['dir']}, {res['refl']} reflections ({kinds.count('v')} on vertical walls, " \
           f"{kinds.count('h')} on horizontal walls); {d1}; {d2}"


def middle_windings(R, S, res):
    """For a y-monotone lighting path, the transverse travel per middle band in units of 2*width."""
    p, q = res['dir']
    s = F(p, q)  # dx/dy, developed slope in the y-chart
    return [abs(s) * R.d / (2 * R.u), abs(s) * R.e / (2 * R.v)]


