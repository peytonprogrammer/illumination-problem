def k0_shot(R, S, T, pq, cap):
    """y-chart with middle gates in their base copies (k=0). Source lift +-x+2wj (source-run windings free),
    source cap optional, terminal +-z (+2W i), terminal cap optional. Return a lift that reproduces the slope."""
    p, q = pq
    s = F(abs(p), abs(q))
    for scap in (False, True):
        a = S[1] - R.y3
        a = 2 * R.c - a if scap else a
        for tcap in (False, True):
            b = R.h - T[1]
            B = 2 * R.h - b if tcap else b
            L = R.d + R.e + B
            for j in range(-40, 41):
                for sgS in (1, -1):
                    for i in (-1, 0, 1):
                        for sgT in (1, -1):
                            X0 = sgS * S[0] + 2 * R.w * j
                            Z = sgT * T[0] + 2 * R.W * i
                            sl = (Z - X0) / (L + a)
                            if abs(sl) != s:
                                continue
                            g = [X0 + sl * (a + t) for t in (0, R.d, R.d + R.e)]
                            if all(abs(x) < wd for x, wd in zip(g, (R.w, R.u, R.v))):
                                return (scap, tcap, j, sl, g, X0, Z)
    return None


