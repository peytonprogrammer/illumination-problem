def lift_dist(z, gens):
    """Distance from z to the group generated by the rational numbers gens."""
    g = F(0)
    for x in gens:
        x = F(x)
        if x == 0:
            continue
        # gcd of rationals
        if g == 0:
            g = abs(x)
        else:
            n = gcd(g.numerator * x.denominator, x.numerator * g.denominator)
            g = F(n, g.denominator * x.denominator)
    r = F(z) - g * floor(F(z) / g)
    return min(r, g - r), g


def Pmid(R):
    return lcm(den(R.d / (2 * R.u)), den(R.e / (2 * R.v)))


def strip_dists(R, S, T):
    """Note 2's necessary projection for the shared-side chart, direct and terminal-cap travel."""
    P = Pmid(R)
    z, b = T[0], R.h - T[1]
    out = []
    for B in (b, 2 * R.h - b):
        dist, g = lift_dist(z, (P * B, 2 * R.W))
        out.append((B, P * B, g, dist))
    return P, out


def swap(p):
    return (p[1], p[0])


