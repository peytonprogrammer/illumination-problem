"""d143 checks for per-class-relay.md (snapshot 2026-11-22 01:25).

Exact integer/Fraction arithmetic on three named rooms only: d141's V-notch B,
d141's four-chamfer octagon O, and the 22-wall room R22 (vertex list copied
from the twenty-two-wall manuscript). No room search and no ray search. No
network.

Method.
* Build the translation unfolding X of each room (d141's tile model, imported
  read-only) and re-tile it by developed unit squares, so X is a square-tiled
  surface over R^2/Z^2 given by right/up permutations r, u.
* Every intermediate translation quotient X -> Y -> R^2/Z^2 with Y of genus
  >= 2 is a block system of <r,u> on the squares of X (zeros of Y lie over the
  origin, so Per(Y) <= Z^2). Enumerate all block systems exactly.
* On each Y, every affine map of derivative -I preserves the square tiling
  (it sends zeros to zeros, so its torus constant is 0 mod Z^2). Enumerate
  them as permutations s with s r = r^-1 s, s u = u^-1 s; keep involutions.
* Genus-one quotients R^2/L (L >= Per(X)) are handled separately: their -I
  involution through f(s), f(t) is z -> pi(s)+pi(t)-z, and every X point over
  the midpoint site maps to a fixed point, so the test reduces to
  "all X points over the X-site are forbidden".
* Midpoint tests, for a source lift s, target lift t, involution e on Y with
  e f(s) = f(t), and holonomy class w in (w0 + Per(X)) / 2Per(X):
    NOTE   : the note's two-site test, Lambda = Per(Y), same-site case only.
             Direction class c is blocked iff sites p and p+c/2 are clean.
    SITE   : one site per holonomy class: w blocked iff the Y-site p + w/2
             (mod Per(Y)) is clean.
    XSITE  : as SITE, but sorting fixed preimages by their X-site
             pi_X(s) + w/2 mod Per(X).
  "Clean" means every X-preimage of an e-fixed point over that site is a
  forbidden corner lift.

Run: python3 -B checks.py > checks.log
"""
