def setup(name, verts):
    room = d141.Room(name, verts, False)
    X, D = build_X(room)
    F = D["forb"]
    systems = all_block_systems(X)
    mechs = []
    ystats = []
    for P in systems:
        Y = quotient(X, P)
        if Y.genus < 2:
            ystats.append((len(set(P)), Y.genus, 0, 0))
            continue
        invs = minus_I_involutions(Y)
        ms = [Mech(X, F, P, Y, s, "deg %d" % (X.n // Y.n)) for s in invs]
        mechs.extend(ms)
        ystats.append((Y.n, Y.genus, len(invs), sum(m.clean_all for m in ms)))
    return room, X, D, systems, mechs, ystats


def site_label(v, L):
    """Label of a half-period v (mod L) as 0, c1, c2, c1+c2 in the HNF basis of L."""
    (a, b), d = L
    v = red(v, L)
    i = v[0] / a
    j = (v[1] - i * b) / d
    return "%s%s" % ("0" if i == 0 else "1/2" if i == Fr(1, 2) else str(i), "," + ("0" if j == 0 else "1/2" if j == Fr(1, 2) else str(j)))


def pair_tests(X, D, mechs, s, t, torus=True):
    """For lift pair (s,t): per holonomy class w in (w0+Per X)/2Per X, which tests block it.
    Returns dict w_label -> set of test names, plus counts."""
    PX = X.Per
    w0 = vsub(X.site(t), X.site(s))
    classes = []
    for (i, j) in ((0, 0), (1, 0), (0, 1), (1, 1)):
        e1, e2 = basis(PX)
        w = vadd(w0, (i * e1[0] + j * e2[0], i * e1[1] + j * e2[1]))
        classes.append(((i, j), w))
    res = {lab: set() for lab, _ in classes}
    nmatch = 0
    notesame = 0
    note_classes = []
    for m in mechs:
        Y, P = m.Y, m.P
        fs, ft = x_point_in_Y(X, Y, P, s), x_point_in_Y(X, Y, P, t)
        if Y.apply_minus(m.s, fs) != ft:
            continue
        nmatch += 1
        p = Y.site(fs)
        # lemma check: every fixed point lies over (pi s + pi t)/2 + 1/2 Per(Y)
        ctr = half(vadd(Y.site(fs), Y.site(ft)))
        for _, ys, _ in m.fix:
            assert contains(Y.Per, (2 * (ys[0] - ctr[0]), 2 * (ys[1] - ctr[1]))), "fixed site off the 4 sites"
        same = contains(Y.Per, w0)
        for lab, w in classes:
            my = red(vadd(p, half(w)), Y.Per)
            mx = red(vadd(X.site(s), half(w)), PX)
            if m.clean_all:
                res[lab].add("FULL")
            if m.ysite_clean(my):
                res[lab].add("SITE")
            if m.xsite_clean(mx):
                res[lab].add("XSITE")
        if same:
            notesame += 1
            # note's two-site test with Lambda = Per(Y): direction classes c blocked
            LY = Y.Per
            bl = []
            for c in basis(LY) + [vadd(*basis(LY))]:
                if m.ysite_clean(red(p, LY)) and m.ysite_clean(red(vadd(p, half(c)), LY)):
                    bl.append(site_label(half(c), LY))
            note_classes.append((m.label, bl))
            if len(bl) == 3:
                for lab, _ in classes:
                    res[lab].add("NOTE")
            else:
                # a w not in 2Per(Y) has a single direction class: blocked if that class is
                for lab, w in classes:
                    if not contains(scale(LY, 2), w):
                        if site_label(half(w), LY) in bl:
                            res[lab].add("NOTE")
    if torus:
        # genus-one quotients: all X points over the X-site must be forbidden
        for lab, w in classes:
            mx = red(vadd(X.site(s), half(w)), PX)
            if torus_site_clean(X, D, mx):
                res[lab].add("TORUS")
    return res, nmatch, notesame, note_classes, w0


_site_cache = {}


def torus_site_clean(X, D, mx):
    key = (id(X), mx)
    if key in _site_cache:
        return _site_cache[key]
    F = D["forb"]
    ok = True
    # X points over mx: centres, edge points, vertices
    for q in range(X.n):
        for loc in ((Fr(1, 2), Fr(1, 2)), (0, Fr(1, 2)), (Fr(1, 2), 0), (0, 0)):
            pt = X.canon(q, loc[0], loc[1])
            if X.site(pt) == mx:
                if not (pt[0] == "p" and pt[1] in F):
                    ok = False
    # non-half-integer X-sites contain only regular points
    if any(c.denominator > 2 for c in mx):
        ok = False
    _site_cache[key] = ok
    return ok


def interior_marks(room):
    """Interior points of the room in (1/2)Z^2 (scaled coordinates)."""
    xs = [v[0] for v in room.P]
    ys = [v[1] for v in room.P]
    out = []
    for x in range(min(xs), max(xs) + 1, 2):
        for y in range(min(ys), max(ys) + 1, 2):
            if d141.inside(room.P, (x, y)) is True:
                out.append((x, y))
    return out


