def section1():
    header("1. Two-site lemma: step counting and site rule (pure lattice arithmetic)")
    lat = [lattice([(1, 0), (0, 1)]), lattice([(2, 0), (0, 2)]), lattice([(1, 1), (1, -1)]), lattice([(4, 4), (4, -4)]),
           lattice([(3, 1), (0, 2)])]
    bad = 0
    tot = 0
    for L in lat:
        e1, e2 = basis(L)
        L2 = scale(L, 2)
        for i in range(-6, 7):
            for j in range(-6, 7):
                if gcd(i, j) != 1:
                    continue
                v = (i * e1[0] + j * e2[0], i * e1[1] + j * e2[1])
                c = red(v, L2)
                for k in range(1, 8):
                    w = (k * v[0], k * v[1])
                    site = red(half(w), L)
                    want = (0, 0) if k % 2 == 0 else red(half(c), L)
                    tot += 1
                    bad += site != want
                    # c/2 well defined: depends only on v mod 2L
                    bad += red(half(c), L) != red(half(v), L)
                    # primitive => nonzero mod 2L
                    bad += c == (0, 0)
    print("  lattices tested %d, (v primitive, k<=7) cases %d, failures %d" % (len(lat), tot, bad))
    print("  midpoint of k*v lies over p for even k and over p + c/2 (c = v mod 2L) for odd k: %s" % (bad == 0))
    print("  sharper form: the site is p + w/2, determined by w mod 2L alone (4 holonomy classes, one site each)")


def run_room(name, verts, show_table=True, generic=None):
    t0 = time.process_time()
    room, X, D, systems, mechs, ystats = setup(name, verts)
    F = D["forb"]
    print("\n[%s] vertices %s" % (name, verts))
    print("  X: %d unit squares, genus %d, %d vertex classes, %d forbidden corner lifts; Per(X) HNF %s (index %d in Z^2)"
          % (X.n, X.genus, X.nv, len(F), X.Per, index(X.Per)))
    nontriv = [y for y in ystats if y[1] >= 2]
    print("  block systems of <r,u> on X squares: %d (genus>=2 quotients %d, genus-1 quotients %d)"
          % (len(systems), len(nontriv), len(ystats) - len(nontriv)))
    print("  quotients Y of genus >= 2: (squares, genus, #-I involutions, #with all fixed preimages forbidden)")
    for y in ystats:
        if y[1] >= 2:
            print("    deg %2d: Y %3d squares, genus %d, %d involutions, %d full-fiber clean"
                  % (X.n // y[0], y[0], y[1], y[2], y[3]))
    print("  genus-1 quotients (squares): %s" % sorted(y[0] for y in ystats if y[1] < 2))
    if show_table:
        print("  per involution: Y-sites (4 sites z with 2z = C_e mod Per(Y)) and fixed preimages [forbidden/regular]")
        for m in mechs:
            sites = {}
            for _, ys, pre in m.fix:
                a = sites.setdefault(ys, [0, 0])
                for _, _, fb in pre:
                    a[0 if fb else 1] += 1
            # include empty sites
            cands = set()
            LY = m.Y.Per
            for hv in [(0, 0)] + basis(LY) + [vadd(*basis(LY))]:
                cands.add(red(vadd(half(m.C), half(hv)), LY))
            row = []
            for z in sorted(cands):
                a = sites.get(z, [0, 0])
                row.append("%s:%d/%d%s" % (site_label(z, LY), a[0], a[1], "*" if a[1] == 0 else ""))
            print("    %s, Y genus %d, Per(Y) index %d: %s%s"
                  % (m.label, m.Y.genus, index(LY), "  ".join(row), "   FULL-CLEAN" if m.clean_all else ""))
        print("    (site label = coordinates of z in the HNF basis of Per(Y); '*' = clean site)")
    hs = corner_only_half_sites(X, D)
    print("  half-integer X-sites (mod Per(X)) carrying only forbidden points: %d of %d: %s"
          % (len(hs[0]), hs[1], sorted(str(tuple(str(c) for c in z)) for z in hs[0])))
    cosets = []
    for z0 in hs[0]:
        co = {red(vadd(z0, half(v)), X.Per) for v in [(0, 0)] + basis(X.Per) + [vadd(*basis(X.Per))]}
        if co <= set(hs[0]) and co not in cosets:
            cosets.append(co)
    print("  full cosets z0 + (1/2)Per(X) of corner-only sites (fixed sites of a torus involution z -> 2 z0 - z"
          " with every fixed preimage forbidden): %d" % len(cosets))
    print("  [setup %.1f CPU-s]" % (time.process_time() - t0))
    return room, X, D, mechs


def corner_only_half_sites(X, D):
    allsites = set()
    for q in range(X.n):
        for loc in ((Fr(1, 2), Fr(1, 2)), (0, Fr(1, 2)), (Fr(1, 2), 0), (0, 0)):
            allsites.add(X.site(X.canon(q, loc[0], loc[1])))
    return [z for z in allsites if torus_site_clean(X, D, z)], len(allsites)


def all_lift_full_fiber(room, X, D, mechs, S, T):
    """Does some Y carry, for EVERY lift pair, a full-fiber-clean e exchanging the images?"""
    lifts = lambda p: sorted({D["lift"](p, g) for g in D["sheets"]}, key=str)
    A, B = lifts(S), lifts(T)
    byY = {}
    for m in mechs:
        byY.setdefault(m.P, []).append(m)
    best = 0
    for P, ms in byY.items():
        Y = ms[0].Y
        good = [m for m in ms if m.clean_all]
        if not good:
            continue
        ok = 0
        for x in A:
            for y in B:
                fx, fy = x_point_in_Y(X, Y, P, x), x_point_in_Y(X, Y, P, y)
                if fx != fy and any(Y.apply_minus(m.s, fx) == fy for m in good):
                    ok += 1
        best = max(best, ok)
    return best, len(A) * len(B)


def section2():
    header("2. Exact replay on the V-notch B and the octagon O")
    out = {}
    for name, verts in (ROOM_B, ROOM_O):
        room, X, D, mechs = run_room(name, verts)
        out[name] = (room, X, D, mechs)
        byY = {}
        for m in mechs:
            byY.setdefault(m.P, []).append(m)
        mx = max([sum(mm.clean_all for mm in ms) for ms in byY.values()] + [0])
        print("  max number of full-fiber-clean involutions on one quotient Y: %d (a generic mark has 8 distinct"
              " images on every Y, so all-lift full-fiber blocking needs >= 8)" % mx)
        # named generic marks from d141
        Sx = (Fr(53, 10), Fr(27, 10))
        if not d141.inside(room.P, Sx):
            Sx = (Sx[0] + 4, Sx[1] + 4)
        s = D["lift"](Sx, d141.I2)
        print("  full-fiber-clean mechanisms (degree, squares of Y): %s"
              % sorted({(X.n // m.Y.n, m.Y.n) for m in mechs if m.clean_all}))
        # half-integer marks: per-class blocking table
        marks = interior_marks(room)
        print("  interior marks in (1/2)Z^2: %d: %s" % (len(marks), " ".join(fmt(p) for p in marks)))
        tot = dict(pairs=0, full=0, site_extra=0, xsite_extra=0, note_extra=0, fully_blocked=[], allLift=0,
                   torus_extra=0, site_not_note=0, exch=0, example=None)
        chords = [0, 0, 0]
        for S, T in combinations(marks, 2):
            tot["pairs"] += 1
            s = D["lift"](S, d141.I2)
            blocked_all = True
            per_t = []
            for g in D["sheets"]:
                t = D["lift"](T, g)
                res, nmatch, notesame, nc, w0 = pair_tests(X, D, mechs, s, t)
                labs = sorted(res)
                full = sum("FULL" in res[l] for l in labs)
                site = sum(bool(res[l] & {"SITE", "XSITE", "TORUS", "NOTE"}) for l in labs)
                tot["full"] += full
                tot["site_extra"] += sum(("SITE" in res[l]) and "FULL" not in res[l] for l in labs)
                tot["xsite_extra"] += sum(("XSITE" in res[l]) and not (res[l] & {"SITE", "FULL"}) for l in labs)
                tot["torus_extra"] += sum(res[l] == {"TORUS"} for l in labs)
                assert all("SITE" in res[l] for l in labs if "NOTE" in res[l]), "NOTE not inside SITE"
                sn = [l for l in labs if "SITE" in res[l] and not (res[l] & {"NOTE", "FULL"})]
                tot["site_not_note"] += len(sn)
                if sn and tot["example"] is None:
                    tot["example"] = (fmt(S), fmt(T), d141.NAME[g], str(w0), sn, {l: sorted(res[l]) for l in labs}, nc)
                tot["exch"] += nmatch > 0
                tot["note_extra"] += sum(("NOTE" in res[l]) and "FULL" not in res[l] for l in labs)
                if site < 4:
                    blocked_all = False
                per_t.append(site)
                # chord consistency on sheet I
                if g == d141.I2 and chord_ok(room, S, T):
                    chords[0] += 1
                    w = (Fr(T[0] - S[0], 4), Fr(T[1] - S[1], 4))
                    e1, e2 = basis(X.Per)
                    for (i, j) in ((0, 0), (1, 0), (0, 1), (1, 1)):
                        cand = vadd(w0, (i * e1[0] + j * e2[0], i * e1[1] + j * e2[1]))
                        if contains(scale(X.Per, 2), vsub(w, cand)):
                            if res[(i, j)]:
                                chords[1] += 1
                    # midpoint fixed by every exchanging e
                    M = ((S[0] + T[0]) / Fr(2), (S[1] + T[1]) / Fr(2))
                    xm = D["lift"](M, d141.I2)
                    for m in mechs:
                        fs, ft = x_point_in_Y(X, m.Y, m.P, s), x_point_in_Y(X, m.Y, m.P, t)
                        if fs != ft and m.Y.apply_minus(m.s, fs) == ft:
                            ym = x_point_in_Y(X, m.Y, m.P, xm)
                            assert m.Y.apply_minus(m.s, ym) == ym, "chord midpoint not fixed"
                            assert m.Y.site(ym) == red(vadd(m.Y.site(fs), half(w)), m.Y.Per), "chord midpoint site"
                            chords[2] += 1
            if blocked_all:
                tot["fully_blocked"].append((fmt(S), fmt(T)))
            best, need = all_lift_full_fiber(room, X, D, mechs, S, T)
            if best == need:
                tot["allLift"] += 1
        print("  pairs %d; (target lift, holonomy class) cells %d" % (tot["pairs"], tot["pairs"] * 8 * 4))
        print("    blocked by a full-fiber-clean involution: %d" % tot["full"])
        print("    blocked by the note's two-site test but not full-fiber: %d" % tot["note_extra"])
        print("    blocked by the one-site (per holonomy class) test but not full-fiber: %d" % tot["site_extra"])
        print("    blocked by the X-site-sorted test but not by SITE or full-fiber: %d" % tot["xsite_extra"])
        print("    blocked only by a corner-only X-site (genus-1 quotient, no involution content): %d" % tot["torus_extra"])
        print("    blocked by the one-site test but by neither the note's two-site test nor full-fiber: %d" % tot["site_not_note"])
        print("    (source on sheet I, target lift) cases with some exchanging -I involution on a genus>=2 quotient: %d of %d"
              % (tot["exch"], tot["pairs"] * 8))
        if tot["example"]:
            print("    example (S, T, target sheet, w0, classes blocked by SITE only, tests per class, note classes per e):")
            print("      %s" % (tot["example"],))
        print("    pairs with every (lift, class) blocked by some midpoint test: %d %s" % (len(tot["fully_blocked"]), tot["fully_blocked"]))
        print("    pairs satisfying the all-lift full-fiber hypothesis on some Y: %d" % tot["allLift"])
        print("  direct chords on sheet I: %d; chord classes reported blocked (would contradict the lemma): %d;"
              " (chord, exchanging e) cases with midpoint e-fixed and over p + w/2: %d" % tuple(chords))
    return out


def section3():
    header("3. R22: is the dark pair S=(0,0), T=(2,2) blocked class by class?")
    room, X, D, mechs = run_room(*ROOM_R22, show_table=False)
    F = D["forb"]
    S, T = (0, 0), (8, 8)
    print("  marks inside: %s %s; sheets %d" % (d141.inside(room.P, S), d141.inside(room.P, T), len(D["sheets"])))
    print("  X-sites (mod Per(X)) of S lifts: %s; of T lifts: %s"
          % (sorted({str(X.site(D["lift"](S, g))) for g in D["sheets"]}),
             sorted({str(X.site(D["lift"](T, g))) for g in D["sheets"]})))
    # lattice sites mod 2Z^2: which contain regular X points
    print("  X points over each lattice class mod 2Z^2 (forbidden / regular), physical points of the regular ones:")
    cls = {}
    for v in range(X.nv):
        q, c = X.vrep[v]
        off = [(0, 0), (1, 0), (1, 1), (0, 1)][c]
        dv = vadd(X.pos[q], off)
        k = (dv[0] % 2, dv[1] % 2)
        a = cls.setdefault(k, [0, 0, set()])
        if v in F:
            a[0] += 1
        else:
            a[1] += 1
            a[2].add(fmt(next(iter(D["vphys"][v]))))
    for k in sorted(cls):
        print("    class %s: %d forbidden, %d regular %s" % (k, cls[k][0], cls[k][1], sorted(cls[k][2])))
    byY = {}
    for m in mechs:
        byY.setdefault(m.P, []).append(m)
    print("  quotients with a -I involution exchanging f(s) and f(t) for some lift pair:")
    s = D["lift"](S, d141.I2)
    union = {}
    for g in D["sheets"]:
        t = D["lift"](T, g)
        res, nmatch, notesame, nc, w0 = pair_tests(X, D, mechs, s, t)
        print("   target sheet %-10s w0=%s: exchanging (Y,e) %d (same-site %d); note-blocked direction classes per e: %s"
              % (d141.NAME[g], w0, nmatch, notesame, nc if nc else "-"))
        for lab in sorted(res):
            print("      holonomy class w0+%s: blocked by %s" % (lab, sorted(res[lab]) if res[lab] else "NOTHING"))
            union[(d141.NAME[g], lab)] = res[lab]
    nb = sum(1 for v in union.values() if not v)
    print("  (target lift, holonomy class) cells: %d; unblocked by every midpoint test: %d" % (len(union), nb))
    # the R22 mechanism: first lattice step lands on an odd site
    print("  R22's own obstruction is not a midpoint: a path with holonomy w in 2Z^2 \\ 0, w = k v (v primitive in Z^2),")
    print("  has k even and passes over s + v, an odd lattice class; check that class membership:")
    for k in sorted(cls):
        if k != (0, 0):
            print("    odd class %s regular X points: %s" % (k, sorted(cls[k][2]) or "none"))
    return union


