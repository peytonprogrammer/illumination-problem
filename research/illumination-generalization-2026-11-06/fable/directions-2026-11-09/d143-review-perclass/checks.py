# ---------------------------------------------------------------- lattices in Z^2
def lattice(vecs):
    """HNF basis ((a,b),(0,d)) of the subgroup of Z^2 generated by vecs."""
    A = (0, 0)
    d = 0
    for v in vecs:
        v = (int(v[0]), int(v[1]))
        while v[0] != 0:
            if A[0] == 0:
                A, v = v, A
                continue
            q = v[0] // A[0]
            v = (v[0] - q * A[0], v[1] - q * A[1])
            if v[0] != 0:
                A, v = v, A
        d = gcd(d, abs(v[1]))
    if A[0] < 0:
        A = (-A[0], -A[1])
    assert A[0] > 0 and d > 0, "not full rank"
    A = (A[0], A[1] % d)
    return (A, d)


def red(v, L):
    (a, b), d = L
    k = (Fr(v[0]) / a).__floor__()
    x = Fr(v[0]) - k * a
    y = Fr(v[1]) - k * b
    y = y - (y / d).__floor__() * d
    return (x, y)


def scale(L, k):
    (a, b), d = L
    return lattice([(k * a, k * b), (0, k * d)])


def basis(L):
    (a, b), d = L
    return [(a, b), (0, d)]


def index(L):
    return L[0][0] * L[1]


def contains(L, v):
    return red(v, L) == (0, 0)


def half(v):
    return (Fr(v[0]) / 2, Fr(v[1]) / 2)


def vadd(a, b):
    return (a[0] + b[0], a[1] + b[1])


def vsub(a, b):
    return (a[0] - b[0], a[1] - b[1])


# ---------------------------------------------------------------- square tiling of X
class Surf:
    """Square-tiled surface: n squares, right/up permutations, vertex classes."""

    def __init__(self, r, u):
        self.n = len(r)
        self.r = r
        self.u = u
        n = self.n
        self.ri = [0] * n
        self.ui = [0] * n
        for i in range(n):
            self.ri[r[i]] = i
            self.ui[u[i]] = i
        # vertex classes of (square, corner) with corners LL=0, LR=1, UR=2, UL=3
        par = list(range(4 * n))

        def f(x):
            while par[x] != x:
                par[x] = par[par[x]]
                x = par[x]
            return x

        def un(a, b):
            a, b = f(a), f(b)
            if a != b:
                par[a] = b
        for q in range(n):
            un(4 * q + 1, 4 * r[q] + 0)
            un(4 * q + 2, 4 * r[q] + 3)
            un(4 * q + 3, 4 * u[q] + 0)
            un(4 * q + 2, 4 * u[q] + 1)
        roots = {}
        self.vc = [0] * (4 * n)
        for x in range(4 * n):
            self.vc[x] = roots.setdefault(f(x), len(roots))
        self.nv = len(roots)
        self.vsize = [0] * self.nv
        for x in range(4 * n):
            self.vsize[self.vc[x]] += 1
        self.vrep = {}
        for x in range(4 * n):
            self.vrep.setdefault(self.vc[x], (x // 4, x % 4))
        chi = self.nv - 2 * n + n
        self.genus = (2 - chi) // 2
        # developed positions and absolute periods
        pos = [None] * n
        pos[0] = (0, 0)
        dq = deque([0])
        per = []
        while dq:
            q = dq.popleft()
            for nb, dv in ((r[q], (1, 0)), (u[q], (0, 1)), (self.ri[q], (-1, 0)), (self.ui[q], (0, -1))):
                p2 = vadd(pos[q], dv)
                if pos[nb] is None:
                    pos[nb] = p2
                    dq.append(nb)
                else:
                    dd = vsub(p2, pos[nb])
                    if dd != (0, 0):
                        per.append(dd)
        assert all(p is not None for p in pos), "disconnected"
        self.pos = pos
        self.Per = lattice(per + [(0, 0)]) if per else None

    def canon(self, q, a, b):
        """Canonical point from square q and local (a,b) in [0,1]^2."""
        a, b = Fr(a), Fr(b)
        while a >= 1:
            q, a = self.r[q], a - 1
        while b >= 1:
            q, b = self.u[q], b - 1
        while a < 0:
            q, a = self.ri[q], a + 1
        while b < 0:
            q, b = self.ui[q], b + 1
        if a == 0 and b == 0:
            return ("p", self.vc[4 * q])
        if a == 0:
            return ("v", q, b)
        if b == 0:
            return ("h", q, a)
        return ("c", q, a, b)

    def site(self, pt):
        """Developed position of a canonical point (mod Per)."""
        if pt[0] == "p":
            q, c = self.vrep[pt[1]]
            off = [(0, 0), (1, 0), (1, 1), (0, 1)][c]
            v = vadd(self.pos[q], off)
        elif pt[0] == "v":
            v = (Fr(self.pos[pt[1]][0]), self.pos[pt[1]][1] + pt[2])
        elif pt[0] == "h":
            v = (self.pos[pt[1]][0] + pt[2], Fr(self.pos[pt[1]][1]))
        else:
            v = (self.pos[pt[1]][0] + pt[2], self.pos[pt[1]][1] + pt[3])
        return red(v, self.Per)

    def apply_minus(self, s, pt):
        """Image of a canonical point under the -I map given by square permutation s."""
        if pt[0] == "c":
            return self.canon(s[pt[1]], 1 - pt[2], 1 - pt[3])
        if pt[0] == "v":
            return self.canon(s[pt[1]], 1, 1 - pt[2])
        if pt[0] == "h":
            return self.canon(s[pt[1]], 1 - pt[2], 1)
        q, c = self.vrep[pt[1]]
        return ("p", self.vc[4 * s[q] + (c + 2) % 4])

    def fixed_points(self, s):
        out = []
        for q in range(self.n):
            if s[q] == q:
                out.append(("c", q, Fr(1, 2), Fr(1, 2)))
            if self.r[s[q]] == q:          # left edge of q is right edge of s(q)
                out.append(("v", q, Fr(1, 2)))
            if self.u[s[q]] == q:
                out.append(("h", q, Fr(1, 2)))
        for v in range(self.nv):
            if self.apply_minus(s, ("p", v)) == ("p", v):
                out.append(("p", v))
        return out


def build_X(room):
    """Square-tile the d141 unfolding X. Returns (Surf, data)."""
    tiles = room.X
    idx = {x: i for i, x in enumerate(tiles)}

    def centre(T):
        return next(v for v in T if v[0] % 4 == 2)

    # spoke components
    par = list(range(len(tiles)))

    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x
    chart = {}
    sq_of = {}
    squares = []
    for x0 in tiles:
        if x0 in sq_of:
            continue
        T0, g0 = x0
        m0 = centre(T0)
        LL = d141.sub(d141.mv(g0, m0), (2, 2))
        comp = {x0: (0, 0)}
        dq = deque([x0])
        while dq:
            x = dq.popleft()
            T, g = x
            m = centre(T)
            t = comp[x]
            for e in combinations(sorted(T), 2):
                if m not in e:
                    continue
                e = frozenset(e)
                kind, T2, rr = room.nb[(T, e)]
                if kind == "int":
                    y, t2 = (T2, g), t
                else:
                    y, t2 = (T, d141.mm(g, rr[0])), d141.add(t, d141.mv(g, rr[1]))
                if y not in comp:
                    comp[y] = t2
                    dq.append(y)
        assert len(comp) == 4, len(comp)
        k = len(squares)
        squares.append(list(comp))
        for x, t in comp.items():
            sq_of[x] = k
            chart[x] = (t, LL)
    n = len(squares)

    def local(x, p):
        T, g = x
        t, LL = chart[x]
        v = d141.sub(d141.add(d141.mv(g, p), t), LL)
        return (Fr(v[0], 4), Fr(v[1], 4))

    r = [None] * n
    u = [None] * n
    for x in tiles:
        T, g = x
        m = centre(T)
        e = frozenset(v for v in T if v != m)
        a, b = sorted(e)
        la, lb = local(x, a), local(x, b)
        mid = ((la[0] + lb[0]) / 2, (la[1] + lb[1]) / 2)
        y = room.xnbr(x, e)
        ya, yb = local(y, a), local(y, b)
        q, q2 = sq_of[x], sq_of[y]
        if mid == (1, Fr(1, 2)):
            r[q] = q2
            assert (ya, yb) == ((la[0] - 1, la[1]), (lb[0] - 1, lb[1])), "right gluing"
        elif mid == (Fr(1, 2), 1):
            u[q] = q2
            assert (ya, yb) == ((la[0], la[1] - 1), (lb[0], lb[1] - 1)), "up gluing"
    assert None not in r and None not in u
    X = Surf(r, u)
    # forbidden vertex classes: X vertices at physical room corners
    forb = set()
    vphys = {}
    for x in tiles:
        T, g = x
        q = sq_of[x]
        for v in T:
            if v[0] % 4 == 0 and v[1] % 4 == 0:
                lv = local(x, v)
                pt = X.canon(q, lv[0], lv[1])
                assert pt[0] == "p"
                vphys.setdefault(pt[1], set()).add(v)
                if v in room.corners:
                    forb.add(pt[1])
    assert all(len(s) == 1 for s in vphys.values()), "vertex class with two physical points"

    def lift(p, g):
        """Canonical X point of physical point p (scaled coords) on sheet g."""
        T = room.containing_tile(p)
        x = (T, g)
        if x not in idx:
            raise ValueError("no tile")
        lp = local(x, p)
        return X.canon(sq_of[x], lp[0], lp[1])
    return X, dict(forb=forb, vphys=vphys, lift=lift, sheets=room.sheets)


# ---------------------------------------------------------------- block systems
def congruence(n, r, u, pairs):
    """Smallest <r,u>-invariant partition containing the pairs (Atkinson)."""
    par = list(range(n))

    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x
    dq = deque(pairs)
    while dq:
        a, b = dq.popleft()
        fa, fb = f(a), f(b)
        if fa == fb:
            continue
        par[fa] = fb
        dq.append((r[fa], r[fb]))
        dq.append((u[fa], u[fb]))
    lab = {}
    return tuple(lab.setdefault(f(x), len(lab)) for x in range(n))


def all_block_systems(X):
    n = X.n
    minimal = {congruence(n, X.r, X.u, [(0, j)]) for j in range(1, n)}
    systems = set(minimal)
    frontier = list(minimal)
    while frontier:
        new = []
        for A in frontier:
            for B in minimal:
                pairs = [(i, j) for i in range(n) for j in (A.index(A[i]), B.index(B[i])) if i != j]
                C = congruence(n, X.r, X.u, pairs)
                if C not in systems:
                    systems.add(C)
                    new.append(C)
        frontier = new
    systems.add(tuple(range(n)))
    return sorted(systems, key=lambda P: -len(set(P)))


def quotient(X, P):
    k = len(set(P))
    r = [None] * k
    u = [None] * k
    for q in range(X.n):
        b = P[q]
        if r[b] is None:
            r[b], u[b] = P[X.r[q]], P[X.u[q]]
        assert r[b] == P[X.r[q]] and u[b] == P[X.u[q]]
    return Surf(r, u)


def minus_I_involutions(Y):
    out = []
    n = Y.n
    for q0 in range(n):
        s = [None] * n
        s[0] = q0
        dq = deque([0])
        ok = True
        while dq and ok:
            q = dq.popleft()
            for nb, img in ((Y.r[q], Y.ri[s[q]]), (Y.u[q], Y.ui[s[q]]),
                            (Y.ri[q], Y.r[s[q]]), (Y.ui[q], Y.u[s[q]])):
                if s[nb] is None:
                    s[nb] = img
                    dq.append(nb)
                elif s[nb] != img:
                    ok = False
                    break
        if ok and len(set(s)) == n and all(s[s[q]] == q for q in range(n)):
            out.append(s)
    return out


def x_point_in_Y(X, Y, P, pt):
    """Image in Y of canonical X point pt."""
    if pt[0] == "p":
        q, c = X.vrep[pt[1]]
        return ("p", Y.vc[4 * P[q] + c])
    if pt[0] == "v":
        return ("v", P[pt[1]], pt[2])
    if pt[0] == "h":
        return ("h", P[pt[1]], pt[2])
    return ("c", P[pt[1]], pt[2], pt[3])


def preimages(X, P, Y, ypt):
    """X preimages of a Y point (canonical)."""
    if ypt[0] in ("v", "h", "c"):
        return [(ypt[0], q) + tuple(ypt[2:]) for q in range(X.n) if P[q] == ypt[1]]
    out = set()
    for x in range(4 * X.n):
        q, c = x // 4, x % 4
        if Y.vc[4 * P[q] + c] == ypt[1]:
            out.add(("p", X.vc[x]))
    return sorted(out)


class Mech:
    """An involution e on a quotient Y, with fixed preimages sorted by Y-site and X-site."""

    def __init__(self, X, F, P, Y, s, label):
        self.P, self.Y, self.s, self.label = P, Y, s, label
        self.fix = []   # (ypt, ysite, [(xpt, xsite, forbidden)])
        for ypt in Y.fixed_points(s):
            pre = [(x, X.site(x), x[0] == "p" and x[1] in F) for x in preimages(X, P, Y, ypt)]
            self.fix.append((ypt, Y.site(ypt), pre))
        y0 = ("c", 0, Fr(1, 3), Fr(1, 5))
        self.C = red(vadd(Y.site(Y.apply_minus(s, y0)), Y.site(y0)), Y.Per)
        self.clean_all = all(fb for _, _, pre in self.fix for _, _, fb in pre)

    def ysite_clean(self, m):
        return all(fb for _, ys, pre in self.fix if ys == m for _, _, fb in pre)

    def xsite_clean(self, mx):
        return all(fb for _, _, pre in self.fix for _, xs, fb in pre if xs == mx)


