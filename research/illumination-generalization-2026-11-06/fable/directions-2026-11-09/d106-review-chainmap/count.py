"""D106 claim 1: exact checks of the corner-incidence count and coset exclusion
on named rooms in d8-perturbation-test/rooms.json. Exact integer arithmetic."""
import json, sys
from math import gcd
from itertools import product
from pathlib import Path
rooms = json.load(open(Path(__file__).resolve().parent.parent / 'd8-perturbation-test/rooms.json'))

def analyse(room):
    cells = {tuple(c) for c in room['cells']}
    n = len(cells)
    pts = {(i + a, j + b) for i, j in cells for a in (0, 1) for b in (0, 1)}
    def star(p):
        x, y = p
        return [c for c in ((x, y), (x-1, y), (x-1, y-1), (x, y-1)) if c in cells]
    k = {}; pinch = 0
    for p in pts:
        s = star(p)
        if len(s) == 2 and s[0][0] != s[1][0] and s[0][1] != s[1][1]:
            pinch += 1
        k[p] = len(s)
    edges = set()
    for i, j in cells:
        edges |= {((i, j), (i+1, j)), ((i, j+1), (i+1, j+1)), ((i, j), (i, j+1)), ((i+1, j), (i+1, j+1))}
    euler = len(pts) - len(edges) + n
    cvx = sum(1 for v in k.values() if v == 1)
    rfx = sum(1 for v in k.values() if v == 3)
    reg = [p for p, v in k.items() if v in (2, 4) and not (v == 2 and p in ())]
    # regular = smooth (2 adjacent cells) or interior (4); pinches excluded above if any
    reg = [p for p in reg if not (k[p] == 2 and len({c[0] for c in star(p)}) == 2 and len({c[1] for c in star(p)}) == 2)]
    regset = set(reg)
    # Identity per class and q_x (Q lifts: smooth 1, interior 2)
    ident_ok = True; q = {}
    for cls in product((0, 1), repeat=2):
        tot = sum(v for p, v in k.items() if (p[0] % 2, p[1] % 2) == cls)
        ident_ok &= (tot == n)
        q[cls] = sum(1 if k[p] == 2 else 2 for p in reg if (p[0] % 2, p[1] % 2) == cls)
    # singular incidences
    sing_inc = sum(1 for (i, j) in cells for a in (0, 1) for b in (0, 1) if (i+a, j+b) not in regset)
    regcount = [sum(1 for a in (0, 1) for b in (0, 1) if (i+a, j+b) in regset) for (i, j) in cells]
    # index of lattice generated by differences of R
    if len(reg) >= 2:
        p0 = reg[0]; diffs = [(p[0]-p0[0], p[1]-p0[1]) for p in reg[1:]]
        det = 0
        for a in diffs:
            for b in diffs:
                det = gcd(det, abs(a[0]*b[1] - a[1]*b[0]))
        index = det if det else 'inf(rank<2)'
    else:
        index = 'inf(|R|<2)'
    return dict(n=n, cvx=cvx, r=rfx, pinch=pinch, euler=euler, ident_ok=ident_ok, q=q,
                sing_inc=sing_inc, maxreg=max(regcount), cells3=sum(1 for c in regcount if c >= 3),
                index=index, reg=reg, k=k, cells=cells)

def subgroups(maxidx):
    # Hermite normal form: rows (a,b),(0,d), a*d = index, 0 <= b < a... use column form
    for a in range(1, maxidx+1):
        for d in range(1, maxidx//a + 1):
            if a*d == 1: continue
            for b in range(d):
                yield (a, b, d)   # lattice generated by (a,0),(b,d)

def coset_of(p, L):
    a, b, d = L
    x, y = p
    t = y % d; y0 = (y - t) // d  # write p = m*(a,0)+y0*(b,d) + rep
    return ((x - y0*b) % a, t)

def coset_test(R, maxidx=6):
    """min over proper subgroups (index <= maxidx) and cosets of #regular Q lifts outside the coset"""
    best = None
    for L in subgroups(maxidx):
        cnt = {}
        for p in R['reg']:
            w = 1 if R['k'][p] == 2 else 2
            c = coset_of(p, L); cnt[c] = cnt.get(c, 0) + w
        tot = sum(cnt.values())
        out = tot - max(cnt.values())
        if best is None or out < best[0]: best = (out, L)
    return best

names = sys.argv[1:] or ['R22-base', 'R34-base']
for nm in names:
    room = next(r for r in rooms if r['id'] == nm)
    R = analyse(room)
    print(f"{nm}: n={R['n']} cvx={R['cvx']} r={R['r']} (cvx-r={R['cvx']-R['r']}) pinch={R['pinch']} euler={R['euler']}")
    print(f"  identity per class: {R['ident_ok']}; Q lifts q_x by class: {R['q']}")
    print(f"  singular incidences={R['sing_inc']} vs 4r+4={4*R['r']+4}; 2r+2={2*R['r']+2}; hypothesis n>2r+2: {R['n'] > 2*R['r']+2}")
    print(f"  regular sites R={sorted(R['reg'])}")
    print(f"  max regular corners in a cell={R['maxreg']}; cells with >=3: {R['cells3']}; index of <R-R> in Z^2: {R['index']}")
    out, L = coset_test(R)
    print(f"  min regular Q lifts outside a proper coset (index<=6): {out} at L={L}; claimed lower bound n-2r-2={R['n']-2*R['r']-2}")

# Whole file: every named room, check the implication and the quantitative bound.
viol = []; hyp = 0; tot = 0; skipped = 0
for room in rooms:
    R = analyse(room)
    if R['pinch'] or R['euler'] != 1 or R['cvx'] - R['r'] != 4:
        skipped += 1; continue
    tot += 1
    assert R['ident_ok'] and R['sing_inc'] == 4*R['r'] + 4, room['id']
    if R['n'] > 2*R['r'] + 2:
        hyp += 1
        out, L = coset_test(R)
        if R['maxreg'] < 3 or R['index'] != 1 or out < R['n'] - 2*R['r'] - 2:
            viol.append((room['id'], R['maxreg'], R['index'], out))
print(f"\nall named rooms: {tot} strictly simple checked, {skipped} skipped (pinch/hole); "
      f"incidence identity sing=4r+4 held in all; {hyp} satisfy n>2r+2; violations: {viol}")

# Detail of the rooms that satisfy n > 2r+2, with their class types.
for room in rooms:
    R = analyse(room)
    if R['n'] > 2*R['r'] + 2:
        types = ''.join('B' if R['q'][c] else 'Q' for c in product((0, 1), repeat=2))
        out, L = coset_test(R)
        print(f"  {room['id']}: n={R['n']} r={R['r']} types(00,01,10,11)={types} maxreg={R['maxreg']} "
              f"index={R['index']} min-outside={out} >= {R['n']-2*R['r']-2}")

