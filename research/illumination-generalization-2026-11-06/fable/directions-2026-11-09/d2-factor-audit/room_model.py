"""Exact models of ONE given lattice room (no room search).

Part A: pillowcase model of the double DP: permutations (lam, rho, the) on cells,
        same conventions as enum_targets.py; block systems; the minimal parity
        congruence B_min generated by transparent non-A lattice points.
Part B: exact, exhaustive illumination relation between regular lattice points,
        by the SL(2,Z) orbit of the 4-fold unfolding (a square-tiled surface).
"""
import sys
from collections import deque

from enum_targets import cycles, ctype, inv, mul

# ---------------------------------------------------------------- geometry


def cells_from_vertices(verts):
    """Unit cells of the simple orthogonal polygon with the given vertex cycle."""
    xs = [x for x, _ in verts]
    ys = [y for _, y in verts]
    out = set()
    m = len(verts)
    for i in range(min(xs), max(xs)):
        for j in range(min(ys), max(ys)):
            cx, cy = i + 0.5, j + 0.5
            inside = False
            for k in range(m):
                (x1, y1), (x2, y2) = verts[k], verts[(k + 1) % m]
                if x1 == x2 and (y1 > cy) != (y2 > cy) and x1 > cx:
                    inside = not inside
            if inside:
                out.add((i, j))
    return out


def around(cells, v):
    x, y = v
    return [c for c in ((x - 1, y - 1), (x, y - 1), (x - 1, y), (x, y)) if c in cells]


def lattice_points(cells):
    pts = set()
    for (i, j) in cells:
        pts |= {(i, j), (i + 1, j), (i, j + 1), (i + 1, j + 1)}
    return pts


def status(cells, v):
    k = len(around(cells, v))
    return {1: "convex", 2: "smooth", 3: "reflex", 4: "interior"}[k]


def cls(v, origin=(0, 0)):
    a, b = (v[0] - origin[0]) % 2, (v[1] - origin[1]) % 2
    return {(0, 0): "A", (1, 0): "C1", (0, 1): "C2", (1, 1): "B"}[(a, b)]


# ---------------------------------------------------------------- Part A


def pillow_model(cells, origin=(0, 0)):
    """Return (index, lam, rho, the) for DP -> pillowcase, A class = origin+2Z^2."""
    cl = sorted(cells)
    idx = {c: k for k, c in enumerate(cl)}
    ox, oy = origin

    def even(c):
        return (c[0] - ox + c[1] - oy) % 2 == 0

    def front(c):
        return (c, 0) if even(c) else (c, 1)

    def cross(face, kind):
        """Cross the edge of the given pillow kind: 'x0','x1','y0','y1'."""
        (i, j), s = face
        axis, par = kind[0], int(kind[1])
        if axis == "x":
            # the cell edge whose x coordinate has parity par (relative to origin)
            xe = i if (i - ox) % 2 == par else i + 1
            nb = (i - 1, j) if xe == i else (i + 1, j)
        else:
            ye = j if (j - oy) % 2 == par else j + 1
            nb = (i, j - 1) if ye == j else (i, j + 1)
        return (nb, s) if nb in cells else ((i, j), 1 - s)

    def back_label(face):
        f = cross(face, "y0")
        assert f == front(f[0])
        return idx[f[0]]

    lam = tuple(back_label(cross(front(c), "x0")) for c in cl)
    rho = tuple(back_label(cross(front(c), "x1")) for c in cl)
    the = tuple(back_label(cross(front(c), "y1")) for c in cl)
    for c in cl:  # labelling convention: back(c) shares the y0 edge with front(c)
        assert back_label(cross(front(c), "y0")) == idx[c]
    return cl, idx, lam, rho, the


def class_perms(lam, rho, the):
    return {"A": lam, "C1": rho, "B": mul(inv(the), rho), "C2": mul(inv(lam), the)}


def closure_partition(n, gens, seed_pairs):
    """Finest G-invariant partition containing the seed pairs (union-find)."""
    par = list(range(n))

    def find(a):
        while par[a] != a:
            par[a] = par[par[a]]
            a = par[a]
        return a

    queue = deque()

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            par[ra] = rb
            queue.append((a, b))

    for a, b in seed_pairs:
        union(a, b)
    allg = list(gens) + [inv(g) for g in gens]
    while queue:
        a, b = queue.popleft()
        for g in allg:
            union(g[a], g[b])
    blocks = {}
    for a in range(n):
        blocks.setdefault(find(a), []).append(a)
    return sorted(blocks.values())


def all_block_systems(n, gens):
    seen = {}
    for b in range(1, n):
        part = closure_partition(n, gens, [(0, b)])
        key = tuple(tuple(x) for x in part)
        seen[key] = part
    return list(seen.values())


def quotient(part, perms):
    bid = {}
    for k, blk in enumerate(part):
        for a in blk:
            bid[a] = k
    out = []
    for p in perms:
        q = [None] * len(part)
        for a in range(len(p)):
            assert q[bid[a]] in (None, bid[p[a]])
            q[bid[a]] = bid[p[a]]
        out.append(tuple(q))
    return bid, out


def group_order(gens, n, cap=2_000_000):
    ident = tuple(range(n))
    seen = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for g in frontier:
            for s in gens:
                h = mul(s, g)
                if h not in seen:
                    seen.add(h)
                    nxt.append(h)
                    if len(seen) > cap:
                        return None
        frontier = nxt
    return len(seen)


# ---------------------------------------------------------------- Part B


def origami(cells):
    """4-fold unfolding: squares (cell, sx, sy); h = right, v = up; lab = actual
    lattice point at the bottom-left corner of each square."""
    sq = [(c, sx, sy) for c in sorted(cells) for sx in (1, -1) for sy in (1, -1)]
    idx = {s: k for k, s in enumerate(sq)}
    h, v, lab = [], [], []
    for (c, sx, sy) in sq:
        i, j = c
        nb = (i + sx, j)
        h.append(idx[(nb, sx, sy)] if nb in cells else idx[(c, -sx, sy)])
        nb = (i, j + sy)
        v.append(idx[(nb, sx, sy)] if nb in cells else idx[(c, sx, -sy)])
        lab.append((i + (1 if sx < 0 else 0), j + (1 if sy < 0 else 0)))
    return sq, tuple(h), tuple(v), lab


def _canon(h, v, lab, starts):
    """Canonical relabelling of (h, v, lab): BFS from each candidate start."""
    best = None
    n = len(h)
    for s in starts:
        new = [-1] * n
        order = [s]
        new[s] = 0
        k = 0
        while k < len(order):
            a = order[k]
            k += 1
            for b in (h[a], v[a]):
                if new[b] < 0:
                    new[b] = len(order)
                    order.append(b)
        key = (tuple(new[h[a]] for a in order), tuple(new[v[a]] for a in order),
               tuple(lab[a] for a in order))
        if best is None or key < best:
            best = key
    return best


BLK, FREE = -1, -2


def illumination(cells, sources, cap=3_000_000, verbose=True):
    """Exact set of sources reached from each source (regular lattice points).

    States are the SL(2,Z) orbit of the 4-fold unfolding, generated by
    U:(h,v)->(h, v h^-1) and L:(h,v)->(h v^-1, v) and inverses.  Under U and L a
    label keeps its bottom-left corner, so the decoration of that corner is
    state independent.  Decoration: index of the source if the corner is a
    source, BLK if it is a genuine room corner, FREE otherwise.  States are
    stored up to decoration-preserving relabelling (canonical form); the scan
    depends only on that class.  In each state follow the rightward horizontal
    ray from every square whose corner is a source: it runs through the corners
    of i, h(i), h^2(i), ... and stops at the first genuine room corner.  Every
    primitive direction is the horizontal direction of some state.
    """
    sq, h0, v0, pts = origami(cells)
    n = len(sq)
    sid = {p: k for k, p in enumerate(sources)}
    lab = tuple(sid[p] if p in sid else
                (BLK if status(cells, p) in ("convex", "reflex") else FREE)
                for p in pts)
    reached = {k: set() for k in range(len(sources))}

    def scan(h, lb):
        for k in range(n):
            s = lb[k]
            if s >= 0:
                cur = h[k]
                while cur != k and lb[cur] != BLK:
                    if lb[cur] >= 0:
                        reached[s].add(lb[cur])
                    cur = h[cur]

    start = _canon(h0, v0, lab, [k for k in range(n) if lab[k] == 0])
    seen = {start}
    queue = deque([start])
    while queue:
        h, v, lb = queue.popleft()
        scan(h, lb)
        hi, vi = inv(h), inv(v)
        anc = [k for k in range(n) if lb[k] == 0]
        for (a, b) in ((h, mul(v, hi)), (h, mul(v, h)), (mul(h, vi), v), (mul(h, v), v)):
            st = _canon(a, b, lb, anc)
            if st not in seen:
                seen.add(st)
                queue.append(st)
                if len(seen) > cap:
                    raise RuntimeError("orbit cap exceeded")
    if verbose:
        print(f"   SL2Z orbit (up to relabelling): {len(seen)} states, {n} squares")
    return {sources[k]: {sources[j] for j in r} for k, r in reached.items()}


# ---------------------------------------------------------------- report


def report(name, verts, origin=(0, 0), do_illum=True):
    cells = cells_from_vertices(verts)
    n = len(cells)
    pts = sorted(lattice_points(cells))
    print(f"=== {name}: area {n}, walls {len(verts)}, origin of A class {origin}")
    st = {p: status(cells, p) for p in pts}
    r = sum(1 for p in pts if st[p] == "reflex")
    print(f"   reflex r={r}, convex={sum(1 for p in pts if st[p]=='convex')}")
    regA = [p for p in pts if cls(p, origin) == "A" and st[p] in ("smooth", "interior")]
    transp = [p for p in pts if cls(p, origin) != "A" and st[p] in ("smooth", "interior")]
    print(f"   regular A points: {[(p, st[p]) for p in regA]}")
    print(f"   transparent non-A points: {[(p, st[p], cls(p, origin)) for p in transp]}")

    cl, idx, lam, rho, the = pillow_model(cells, origin)
    cp = class_perms(lam, rho, the)
    print("   cycle types on DP:", {k: ctype(p) for k, p in cp.items()})
    gens = (lam, rho, the)
    order = group_order(gens, n)
    print(f"   |monodromy group| = {order if order else '> cap'}")
    systems = all_block_systems(n, gens)
    seeds = []
    for k in ("C1", "B", "C2"):
        for c in cycles(cp[k]):
            if len(c) == 2:
                seeds.append(c)
    bmin = closure_partition(n, gens, seeds)
    print(f"   block systems from pairs (0,b): sizes {sorted(len(p) for p in systems)} blocks")
    print(f"   B_min: {len(bmin)} blocks of size {sorted(set(len(b) for b in bmin))}")
    bid, (ql, qr, qt) = quotient(bmin, (lam, rho, the))
    qcp = class_perms(ql, qr, qt)
    print("   N_min cycle types:", {k: ctype(p) for k, p in qcp.items()})
    print(f"   N_min perms: lam={ql} rho={qr} the={qt}")
    for part in systems:
        _, (a, b, c) = quotient(part, (lam, rho, the))
        q = class_perms(a, b, c)
        par = all(set(ctype(q[k])) <= {1, 3} for k in ("C1", "B", "C2"))
        print(f"     block system with {len(part)} blocks: parity property {par};"
              f" types { {k: ctype(p) for k, p in q.items()} }")

    # fibres of N_min over A points: lifts of each regular A point
    acyc = {}
    for c in cycles(ql):
        for b in c:
            acyc[b] = (len(c), min(c))

    def lifts(p):
        cs = around(cells, p)
        ox, oy = origin
        ev = [c for c in cs if (c[0] - ox + c[1] - oy) % 2 == 0]
        od = [c for c in cs if (c[0] - ox + c[1] - oy) % 2 == 1]
        if st[p] == "interior":
            return [ev, od]          # top lift, bottom lift
        return [ev + od]             # one point of DP

    img = {}
    for p in regA:
        img[p] = []
        for lift in lifts(p):
            im = {acyc[bid[idx[c]]] for c in lift}
            assert len(im) == 1, (p, im)
            img[p].append(im.pop())
        print(f"   phi_min({p}) = {img[p]}   (cone angle/pi, id)")

    if do_illum and len(regA) >= 2:
        reach = illumination(cells, regA)
        print("   exact illumination among regular A points (x = lit, . = dark):")
        for p in regA:
            row = " ".join("x" if q in reach[p] else "." for q in regA)
            print(f"     {str(p):>9}: {row}")
        ok = True
        for p in regA:
            for q in regA:
                if p == q:
                    continue
                lit = q in reach[p]
                # certified dark iff no lift of p shares an image with a lift of q
                same = bool(set(img[p]) & set(img[q]))
                if lit and not same:
                    print(f"   !! {p}->{q} lit but separated by N_min (BUG)")
                    ok = False
                if (not lit) and same:
                    print(f"   ** {p}->{q} DARK but NOT separated by N_min")
                    ok = False
        print("   conjecture 'dark <=> separated by N_min' on these points:",
              "HOLDS" if ok else "FAILS (see ** lines)")
    return cells


