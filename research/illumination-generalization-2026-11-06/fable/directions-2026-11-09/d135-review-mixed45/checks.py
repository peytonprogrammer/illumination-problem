# order type of arrangement along a named one-parameter family: chamfered square L=6, chamfer t
def arrangement_signature(P, marks):
    pts = list(P) + list(marks)
    lines = set()
    for (x, y) in pts:
        for k, nrm in fams.items(): lines.add((nrm, nrm[0]*x + nrm[1]*y))
    lines = sorted(lines)
    sig = []
    for (n1, c1) in lines:
        # parametrize along the line by t = tangent coordinate
        tan = (-n1[1], n1[0])
        vals = []
        for (n2, c2) in lines:
            det = n1[0]*n2[1]-n1[1]*n2[0]
            if det == 0: continue
            x = F(c1*n2[1]-c2*n1[1], det); y = F(n1[0]*c2-n2[0]*c1, det)
            vals.append(tan[0]*x + tan[1]*y)
        sig.append(tuple(sgn(u-v) for u, v in itertools.combinations(vals, 2)))
    par = tuple(sgn(c1-c2) for (n1,c1),(n2,c2) in itertools.combinations(lines, 2) if n1 == n2)
    return (len(lines), tuple(sig), par)

