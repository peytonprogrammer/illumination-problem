def trace(P, S, d, T, cap=200):
    n = len(P); pos = (F(S[0]), F(S[1])); d = (F(d[0]), F(d[1])); T = (F(T[0]), F(T[1]))
    seen = set()
    for step in range(cap):
        if (pos, d) in seen: return ("periodic, never meets T", step, pos)
        seen.add((pos, d))
        best = None
        for i in range(n):
            p, q = P[i], P[(i+1) % n]
            ex, ey = q[0]-p[0], q[1]-p[1]
            den = d[0]*ey - d[1]*ex
            if den == 0: continue
            s = ((p[0]-pos[0])*ey - (p[1]-pos[1])*ex) / den
            u = ((p[0]-pos[0])*d[1] - (p[1]-pos[1])*d[0]) / den
            if s > 0 and 0 <= u <= 1 and (best is None or s < best[0]): best = (s, i, u)
        s, i, u = best
        # target on the open segment before the hit?
        cr = (T[0]-pos[0])*d[1] - (T[1]-pos[1])*d[0]
        if cr == 0:
            st = (T[0]-pos[0])/d[0] if d[0] else (T[1]-pos[1])/d[1]
            if 0 < st < s: return ("lit", step, pos)
        hit = (pos[0]+s*d[0], pos[1]+s*d[1])
        if u in (0, 1): return ("corner", step, hit)
        k = dir_index(P[(i+1)%n][0]-P[i][0], P[(i+1)%n][1]-P[i][1])
        Rm = refl(k); d = (Rm[0][0]*d[0]+Rm[0][1]*d[1], Rm[1][0]*d[0]+Rm[1][1]*d[1])
        pos = hit
        if step < 4: print(f"     bounce {step}: at {tuple(map(str,hit))} on edge {P[i]}->{P[(i+1)%n]}, new dir {tuple(map(str,d))}")
    return ("cap", cap, pos)
