"""Twist lemma test.

For a state t and an arc a-x, let h = g_a g_x in the arc-adapted order.  If a power k = h^m
commutes with g_a and g_x, then m full twists about a and x return the same tuple and move
the points over a by k (Lemma T, notes.md).  The script
  1. verifies the claim literally for the arc a-b with pure_move (tuple and labels);
  2. computes the group W generated by all twist elements, transported to the base state
     along a spanning tree of the plain pure-braid orbit, and compares it with the group M
     of mine.py (W is a subgroup of M);
  3. counts the orbits where some twist element is a transposition of two regular a-points.
"""
import sys, json
from collections import deque, Counter
from math import factorial
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'd6-hurwitz-census'))
from hurwitz import mul, inv, cycles, move, pure_move, PURE_GENS, canon_plain, initial_pt
LABELS = ('a', 'b', 'c', 'd')

def group_order(gens, q):
    e = tuple(range(q)); seen = {e}; fr = [e]
    while fr:
        nf = []
        for g in fr:
            for s in gens:
                x = tuple(s[g[i]] for i in range(q))
                if x not in seen:
                    seen.add(x); nf.append(x)
        fr = nf
    return len(seen), seen

def twist_elements(t, pt, ids):
    """Label permutations induced by h^m, over the three arcs, with m minimal per coset."""
    n = len(t[0]); e = tuple(range(n)); out = []
    for x in (1, 2, 3):
        ga, gx = t[0], t[x]
        h = mul(ga, gx) if x != 3 else mul(gx, ga)
        k = h; m = 1
        while k != e:
            if mul(k, ga) == mul(ga, k) and mul(k, gx) == mul(gx, k):
                pi = [None] * len(ids)
                for i in range(n):
                    if pt[i] >= 0:
                        pi[ids[pt[i]]] = ids[pt[k[i]]]
                out.append((x, m, tuple(pi)))
            k = mul(k, h); m += 1
    return out

for n in [int(a) for a in sys.argv[1:]]:
    d = json.loads((HERE / f'mine_n{n}.json').read_text())
    S = Counter()
    for o in d['orbits']:
        t0 = tuple(tuple(g) for g in o['rep'])
        cid, plen = initial_pt(t0[0])
        pt0 = tuple(c if plen[c] == 2 else -1 for c in cid)
        ids = {c: j for j, c in enumerate(sorted(set(p for p in pt0 if p >= 0)))}
        q = len(ids)
        seen = {canon_plain(t0)}; queue = deque([(t0, pt0)])
        gens = set(); checked = 0
        while queue:
            t, pt = queue.popleft()
            for (x, m, pi) in twist_elements(t, pt, ids):
                gens.add(pi)
                if x == 1 and checked < 3 and m <= 60:      # literal check on the arc a-b
                    u, pu = t, pt
                    for _ in range(m):
                        u, _, pu = pure_move(u, LABELS, pu, 0, +1)
                    assert u == t, 'tuple does not return'
                    got = [None] * q
                    for i in range(n):
                        if pt[i] >= 0:
                            got[ids[pt[i]]] = ids[pu[i]]
                    inv_pi = [None] * q
                    for a_, b_ in enumerate(pi):
                        inv_pi[b_] = a_
                    assert tuple(got) in (pi, tuple(inv_pi)), (got, pi)
                    checked += 1; S['literal checks passed (arc a-b)'] += 1
            for (i, s) in PURE_GENS:
                t2, _, pt2 = pure_move(t, LABELS, pt, i, s)
                c = canon_plain(t2)
                if c not in seen:
                    seen.add(c); queue.append((t2, pt2))
        w, elems = group_order(list(gens) or [tuple(range(q))], q)
        has_transp = any(sum(1 for i in range(q) if g[i] != i) == 2 for g in gens)
        assert o['M_order'] % w == 0, (o['cts'], w, o['M_order'])
        prim = o.get('primitive'); degenerate = any(len(c) == n for c in o['cts'])
        key = 'G primitive' if prim else 'G imprimitive'
        S[(key, 'orbits')] += 1
        S[(key, 'W = M')] += (w == o['M_order'])
        S[(key, 'M = S_q')] += (o['M_order'] == factorial(q))
        S[(key, 'W = S_q')] += (w == factorial(q))
        S[(key, 'twist transposition exists')] += has_transp
        if prim and not degenerate and o['M_order'] == factorial(q) and w != factorial(q):
            S[(key, 'M = S_q but W smaller')] += 1
            if S['shown'] < 4:
                S['shown'] += 1
                print('   W < M = S_q:', n, o['cts'], 'q', q, '|W|', w, 'plain', o['plain'])
    print(n)
    for k_, v in sorted(S.items(), key=str):
        print('   ', k_, v)
