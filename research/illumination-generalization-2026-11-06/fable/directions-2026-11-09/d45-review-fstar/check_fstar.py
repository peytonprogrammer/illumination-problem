"""d45: independent check of F* on named rooms. No roomtools, no ray search.

Builds the fold monodromy DP -> PC from edge involutions, computes B_x (congruence
generated by the 2-cycles of sigma_x), and for each class quotient checks:
zero fibres have delta unramified reflex preimages in one parity class, the
F* inequality, and the F* pass with the r <= 8 cap lifted.
"""
import resource, sys
resource.setrlimit(resource.RLIMIT_CPU, (60, 60))

R22 = [(-1, -1), (-1, 1), (0, 1), (0, 2), (1, 2), (1, 3), (3, 3), (3, 2), (4, 2), (4, 1), (5, 1),
       (5, 0), (3, 0), (3, 1), (1, 1), (1, -1), (2, -1), (2, -3), (1, -3), (1, -2), (0, -2), (0, -1)]

def cells_in(poly):
    xs = [p[0] for p in poly]; ys = [p[1] for p in poly]
    out = set()
    for i in range(min(xs), max(xs)):
        for j in range(min(ys), max(ys)):
            px, py = i + .5, j + .5; inside = False
            for k in range(len(poly)):
                (x1, y1), (x2, y2) = poly[k], poly[(k + 1) % len(poly)]
                if (y1 > py) != (y2 > py) and px < x1 + (py - y1) * (x2 - x1) / (y2 - y1):
                    inside = not inside
            if inside:
                out.add((i, j))
    return out

Q = {(0, 0), (1, 0), (1, 1), (2, 1), (2, 2)}
P6 = Q | {(i, -j - 1) for i, j in Q} | {(5 - i, -j - 1) for i, j in Q} | {(i, 5 - j) for i, j in Q}
CROSS = {(i, j) for i in range(4) for j in range(1, 3)} | {(i, j) for i in range(1, 3) for j in range(4)}

def monodromy(cells):
    cl = sorted(cells); idx = {c: k for k, c in enumerate(cl)}
    def kap(axis, par):  # involution across grid lines with coordinate parity par on axis
        p = []
        for (i, j) in cl:
            v = (i, j)[axis]; lo = v if v % 2 == par else v + 1  # the line of that parity bounding the cell
            step = -1 if lo == v else 1
            nb = (i + step, j) if axis == 0 else (i, j + step)
            p.append(idx.get(nb, idx[(i, j)]))
        return p
    kv = {0: kap(0, 0), 1: kap(0, 1)}; kh = {0: kap(1, 0), 1: kap(1, 1)}
    sig = {}
    for a in (0, 1):
        for b in (0, 1):
            sig[(a, b)] = [kv[a][kh[b][k]] for k in range(len(cl))]
    return cl, sig

def cycles(p, n):
    seen = [False] * n; out = []
    for s in range(n):
        if not seen[s]:
            c = []; x = s
            while not seen[x]:
                seen[x] = True; c.append(x); x = p[x]
            out.append(c)
    return out

def congruence(n, gens, pairs):
    par = list(range(n))
    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    todo = list(pairs)
    while todo:
        a, b = todo.pop(); ra, rb = f(a), f(b)
        if ra == rb:
            continue
        par[ra] = rb
        for g in gens:
            todo.append((g[a], g[b]))
    blocks = {}
    for x in range(n):
        blocks.setdefault(f(x), []).append(x)
    return [f(x) for x in range(n)], list(blocks.values())

def reflex_rho(cells):
    pts = {(x + u, y + w) for (x, y) in cells for u in (0, 1) for w in (0, 1)}
    rho = [0] * 4; r = 0
    for (x, y) in pts:
        if sum((x - 1 + u, y - 1 + w) in cells for u in (0, 1) for w in (0, 1)) == 3:
            r += 1; rho[(x % 2) * 2 + (y % 2)] += 1
    return r, rho

def zmin(d):
    return -(-(d - 1) // 4) if d % 2 else -(-d // 4)

def fstar(rho, n, r):  # my own statement of F*, no r cap
    hits = []
    for delta in range(3, n + 1):
        if n % delta: continue
        d = n // delta
        if d < 2: continue
        z0 = zmin(d)
        if z0 * delta <= r and sum(x // delta for x in rho) >= z0:
            hits.append((delta, d, z0))
    return hits

for name, cells in [('22-wall', cells_in(R22)), ('P6', P6), ('cross', CROSS)]:
    n = len(cells); r, rho = reflex_rho(cells)
    cl, sig = monodromy(cells)
    # sanity: reflex corners = 3-cycles of the sigmas
    n3 = sum(1 for s in sig.values() for c in cycles(s, n) if len(c) == 3)
    print('==', name, 'n', n, 'r', r, 'rho', rho, '3-cycles', n3, 'F* hits (no cap)', fstar(rho, n, r))
    gens = list(sig.values())
    for x, s in sig.items():
        pairs = [(c[0], c[1]) for c in cycles(s, n) if len(c) == 2]
        lab, blocks = congruence(n, gens, pairs)
        nb = len(blocks); delta = n // nb
        if nb == 1:
            print('  class', x, 'one block'); continue
        # points of N over each corner y: cycles of sigma_y on blocks
        zeros = 0; ok = True; galois_fibres = True
        bid = {b: k for k, b in enumerate(sorted(set(lab)))}
        for y, sy in sig.items():
            bp = [None] * nb
            for k in range(n):
                bp[bid[lab[k]]] = bid[lab[sy[k]]]
            for bc in cycles(bp, nb):
                L = len(bc); bs = set(bc)
                up = [c for c in cycles(sy, n) if bid[lab[c[0]]] in bs]
                es = sorted(len(c) // L for c in up)
                if len(set(es)) > 1: galois_fibres = False
                if L == 3:
                    zeros += 1
                    if not (len(up) == delta and all(len(c) == 3 for c in up)):
                        ok = False
        print('  class', x, 'blocks', nb, 'delta', delta, 'd', nb, 'z', zeros,
              'zero fibres = delta reflex corners of class', x if False else 'y', ok,
              'equal local degrees in every fibre', galois_fibres,
              'sum floor(rho/delta) >= z', sum(v // delta for v in rho) >= zeros if delta > 0 else None)
