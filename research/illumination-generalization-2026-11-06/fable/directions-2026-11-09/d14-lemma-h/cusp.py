"""Cusp subgroup of the point monodromy group M_t, on the saved d12 orbit list.

For every saved orbit with q >= 2 regular a-points (representatives from
../d12-lit-side/mine_nN.json; no new covers are enumerated) the script walks the
PLAIN pure-braid orbit and computes, as permutation groups on the q regular a-points:

  M    : group generated by the Schreier generators of the stabiliser of the base
         tuple (generators s0^2, s1^2 and inverses), deck maps included.
  N    : group generated by every cusp loop (T_x)^w at every state, x in {b, c, d},
         where T_b = s0^2, T_d = s1^2, T_c = s0 s1^2 s0^-1 and w is the first return
         time to the same tuple up to conjugation.  N is normal in M.
  N_x  : the same with one cusp type x.

Label permutations are expressed on the global point IDs, so loops based at any state
are automatically transported to the base state.

Run: python3 -B cusp.py N [workers]   -> cusp_nN.json
"""
import json
import sys
import time
from collections import deque
from multiprocessing import Pool
from pathlib import Path

HERE = Path(__file__).resolve().parent
D6 = HERE.parent / 'd6-hurwitz-census'
D12 = HERE.parent / 'd12-lit-side'
sys.path.insert(0, str(D6))
from hurwitz import move, pure_move, canon_plain, initial_pt, PURE_GENS  # noqa: E402

LABELS = ('a', 'b', 'c', 'd')


def twist(t, pt, x):
    """One full twist about the arc a-x (x = 1, 2, 3)."""
    if x == 1:
        t, _, pt = pure_move(t, LABELS, pt, 0, +1)
    elif x == 3:
        t, _, pt = pure_move(t, LABELS, pt, 1, +1)
    else:
        t, lab, pt = move(t, LABELS, pt, 0, +1)
        t, lab, pt = move(t, lab, pt, 1, +1)
        t, lab, pt = move(t, lab, pt, 1, +1)
        t, lab, pt = move(t, lab, pt, 0, -1)
        assert lab == LABELS
    return t, pt


def closure(gens, q):
    e = tuple(range(q))
    seen = {e}
    fr = [e]
    gens = [g for g in set(gens) if g != e]
    while fr:
        nf = []
        for g in fr:
            for s in gens:
                x = tuple(s[i] for i in g)
                if x not in seen:
                    seen.add(x)
                    nf.append(x)
        fr = nf
    return seen


def orbit_counts(group, q):
    pts = len({min(g[i] for g in group) for i in range(q)})
    prs = len({min(tuple(sorted((g[i], g[j]))) for g in group)
               for i in range(q) for j in range(i + 1, q)})
    return pts, prs


def analyse(job):
    n, o = job
    t0 = tuple(tuple(g) for g in o['rep'])
    cid, plen = initial_pt(t0[0])
    pt0 = tuple(c if plen[c] == 2 else -1 for c in cid)
    ids = sorted({p for p in pt0 if p >= 0})
    idx = {p: k for k, p in enumerate(ids)}
    q = len(ids)

    def canon_pt(t, pt):
        """plain canonical form and the list of ID arrays in canonical sheet order."""
        pc, labs = canon_plain(t, want_map=True)
        out = []
        for lab in labs:
            arr = [0] * n
            for s in range(n):
                arr[lab[s]] = pt[s]
            out.append(arr)
        return pc, out

    def perms(ref, arrs):
        res = []
        for arr in arrs:
            pi = [None] * q
            for c in range(n):
                u, v = ref[c], arr[c]
                assert (u < 0) == (v < 0)
                if u >= 0:
                    assert pi[idx[u]] in (None, idx[v])
                    pi[idx[u]] = idx[v]
            res.append(tuple(pi))
        return res

    pc0, arrs0 = canon_pt(t0, pt0)
    ref = {pc0: arrs0[0]}
    states = {pc0: (t0, pt0)}
    queue = deque([pc0])
    gensM = set(perms(arrs0[0], arrs0))          # deck maps
    while queue:
        pc = queue.popleft()
        t, pt = states[pc]
        for (i, s) in PURE_GENS:
            t2, _, pt2 = pure_move(t, LABELS, pt, i, s)
            pc2, arrs2 = canon_pt(t2, pt2)
            if pc2 not in ref:
                ref[pc2] = arrs2[0]
                states[pc2] = (t2, pt2)
                queue.append(pc2)
            gensM.update(perms(ref[pc2], arrs2))
    assert len(ref) == o['plain']
    gensN = {1: set(), 2: set(), 3: set()}
    ncusps = {1: 0, 2: 0, 3: 0}
    # links: a 2-cycle of g_x whose two sheets lie in two distinct 2-cycles of g_a
    link_states = [0, 0, 0, 0]          # states with a link at b, c, d, any
    for pc, (t, pt) in states.items():
        anyl = False
        for x in (1, 2, 3):
            gx = t[x]
            has = any(gx[gx[i]] == i and gx[i] > i and pt[i] >= 0 and pt[gx[i]] >= 0
                      and pt[i] != pt[gx[i]] for i in range(n))
            link_states[x - 1] += has
            anyl = anyl or has
        link_states[3] += anyl
    t, pt = t0, pt0
    base_link = [any(t[x][t[x][i]] == i and t[x][i] > i and pt[i] >= 0 and pt[t[x][i]] >= 0
                     and pt[i] != pt[t[x][i]] for i in range(n)) for x in (1, 2, 3)]
    single = {'transposition': 0, '3-cycle': 0}
    for x in (1, 2, 3):
        done = set()
        for pc in ref:
            if pc in done:
                continue
            ncusps[x] += 1
            # walk the T_x cycle through pc; every state on it gets the loop T_x^w
            cyc = []
            t, pt = states[pc]
            cur = pc
            while True:
                cyc.append(cur)
                done.add(cur)
                t, pt = twist(t, pt, x)
                cur, arrs = canon_pt(t, pt)
                if cur == pc:
                    break
            w = len(cyc)
            for u in cyc:
                t, pt = states[u]
                for _ in range(w):
                    t, pt = twist(t, pt, x)
                cu, arrs = canon_pt(t, pt)
                assert cu == u
                ps = perms(ref[u], arrs)
                gensN[x].update(ps)
                for p in ps:
                    moved = sum(1 for i in range(q) if p[i] != i)
                    if moved == 2:
                        single['transposition'] += 1
                    if moved == 3:
                        single['3-cycle'] += 1
    M = closure(gensM, q)
    assert len(M) == o['M_order'], (len(M), o['M_order'])
    allN = set().union(*gensN.values())
    N = closure(allN, q)
    assert N <= M
    rec = dict(n=n, cts=o['cts'], rep=o['rep'], order=o['order'], primitive=o['primitive'],
               contains_An=o['contains_An'], plain=o['plain'], q=q, deck_order=o['deck_order'],
               M_order=len(M), M_orbits=orbit_counts(M, q),
               N_order=len(N), N_orbits=orbit_counts(N, q),
               ncusps=[ncusps[x] for x in (1, 2, 3)],
               gensM=sorted(g for g in gensM if g != tuple(range(q))),
               gensN=[sorted(g for g in gensN[x] if g != tuple(range(q))) for x in (1, 2, 3)],
               link_states=link_states, base_link=base_link,
               single_cusp_transposition=single['transposition'] > 0,
               single_cusp_3cycle=single['3-cycle'] > 0)
    for x in (1, 2, 3):
        Nx = closure(gensN[x], q)
        rec[f'N{"abcd"[x]}_order'] = len(Nx)
        rec[f'N{"abcd"[x]}_orbits'] = orbit_counts(Nx, q)
    genus2 = 2 - (-o['plain'] + sum(ncusps.values()))   # 2g = 2 - chi
    assert genus2 % 2 == 0, 'Euler characteristic parity: third cusp convention is wrong'
    rec['hurwitz_genus'] = genus2 // 2
    return rec


def main():
    n = int(sys.argv[1])
    workers = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    d = json.loads((D12 / f'mine_n{n}.json').read_text())
    jobs = []
    for o in d['orbits']:
        jobs.append((n, {k: o[k] for k in ('cts', 'rep', 'order', 'primitive', 'contains_An',
                                            'plain', 'deck_order', 'M_order')}))
    del d
    jobs.sort(key=lambda j: -j[1]['plain'])
    t0 = time.time()
    out = []
    with Pool(workers) as pool:
        for k, rec in enumerate(pool.imap_unordered(analyse, jobs, chunksize=1)):
            out.append(rec)
            if k % 200 == 0:
                print(n, k, len(jobs), round(time.time() - t0), flush=True)
    (HERE / f'cusp_n{n}.json').write_text(json.dumps(dict(n=n, orbits=out), separators=(',', ':')) + '\n')
    print('done', n, len(out), 'orbits', round(time.time() - t0), 's')


if __name__ == '__main__':
    main()
