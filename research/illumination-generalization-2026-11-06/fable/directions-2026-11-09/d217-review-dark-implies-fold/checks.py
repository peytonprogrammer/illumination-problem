K = importlib.util.module_from_spec(spec); spec.loader.exec_module(K)
trace, vertex_counts, strictly_simple = K.trace, K.vertex_counts, K.strictly_simple

T0 = time.process_time()
FAILS = []


def say(*a):
    print(*a, flush=True)


def check(cond, msg):
    say(("PASS " if cond else "FAIL ") + msg)
    if not cond:
        FAILS.append(msg)


def ncells(c, p):
    x, y = p
    return [(x - 1, y - 1) in c, (x, y - 1) in c, (x - 1, y) in c, (x, y) in c]


def kind(c, p):
    bl, br, tl, tr = ncells(c, p)
    n = bl + br + tl + tr
    if n == 4: return "interior"
    if n == 3: return "reflex"
    if n == 1: return "convex"
    if n == 2: return "pinch" if bl == tr else "smooth"
    return "out"


def points(c):
    return {(x + dx, y + dy) for (x, y) in c for dx in (0, 1) for dy in (0, 1)}


def par(p):
    return (p[0] % 2, p[1] % 2)


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))


# ------------------------------------------------------------------ rooms
ROOMS = json.load(open(os.path.join(DIRS, "d8-perturbation-test", "rooms.json")))
R34rec = next(r for r in ROOMS if r["id"] == "R34-base")
R34 = {tuple(c) for c in R34rec["cells"]}
P0 = [(-1, -1), (0, -1), (0, -2), (1, -2), (1, -3)]
R22 = set(P0) | {(x, -y - 1) for (x, y) in P0} | {(3 - x, -y - 1) for (x, y) in P0}
Qp = {(0, 0), (1, 0), (1, 1), (2, 1), (2, 2)}
P6 = Qp | {(i, -j - 1) for i, j in Qp} | {(5 - i, -j - 1) for i, j in Qp} | {(i, 5 - j) for i, j in Qp}


def summary(nm, c):
    pts = points(c)
    ks = {p: kind(c, p) for p in pts}
    reg = sorted(p for p in pts if ks[p] in ("interior", "smooth"))
    rx, cv, pin = vertex_counts(c)
    say(f"  {nm}: area {len(c)}, reflex {rx}, convex {cv}, pinch {pin}, walls {rx + cv}, "
        f"strictly simple {strictly_simple(c)}")
    say(f"    regular sites: " + ", ".join(f"{p}:{ks[p]}:{par(p)}" for p in reg))
    return ks, reg


def local_count(c, S, T):
    """Claim 4 instance: axial neighbours of S,T reflex and distinct; some off-class
    diagonal neighbour reflex and of (odd,odd) relative parity."""
    ax = [(m[0] + dx, m[1] + dy) for m in (S, T) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
    axial_ok = all(kind(c, p) == "reflex" for p in ax) and len(set(ax)) == 8
    diag = [(S[0] + dx, S[1] + dy) for dx in (1, -1) for dy in (1, -1)]
    ninth = [p for p in diag if kind(c, p) == "reflex"]
    rel = {((p[0] - S[0]) % 2, (p[1] - S[1]) % 2) for p in ninth}
    return axial_ok, ninth, rel


# ------------------------------------------------------------------ claim 1
def claim1():
    say("\n=== Claim 1: finest G-invariant equivalence containing A (abstract group, 6 points)")
    # G = dihedral group of the hexagon on {0..5}; generated by rotation and a reflection.
    rot = (1, 2, 3, 4, 5, 0); ref = (0, 5, 4, 3, 2, 1)
    G = {tuple(range(6))}
    frontier = list(G)
    while frontier:
        g = frontier.pop()
        for h in (rot, ref):
            k = tuple(h[g[i]] for i in range(6))
            if k not in G: G.add(k); frontier.append(k)
    check(len(G) == 12, "D6 has order 12")

    def closure(A):
        parent = list(range(6))
        def f(i):
            while parent[i] != i: i = parent[i]
            return i
        for (i, j) in A:
            for g in G:
                a, b = f(g[i]), f(g[j])
                if a != b: parent[a] = b
        comps = {}
        for i in range(6): comps.setdefault(f(i), set()).add(i)
        return frozenset(frozenset(s) for s in comps.values())

    def partitions(s):
        if not s: yield []; return
        a, rest = s[0], s[1:]
        for p in partitions(rest):
            for i in range(len(p)):
                yield p[:i] + [p[i] | {a}] + p[i + 1:]
            yield p + [{a}]

    allp = [frozenset(frozenset(b) for b in p) for p in partitions(list(range(6)))]

    def invariant(P):
        return all(frozenset(frozenset(g[i] for i in b) for b in P) == P for g in G)

    def contains(P, A):
        return all(any(i in b and j in b for b in P) for (i, j) in A)

    def refines(P, Qq):
        return all(any(b <= c for c in Qq) for b in P)

    ok = True; nprop = 0
    for A in ([(0, 3)], [(0, 2)], [(0, 1)], [(0, 2), (0, 3)]):
        C = closure(A)
        cands = [P for P in allp if invariant(P) and contains(P, A)]
        finest = all(refines(C, P) for P in cands) and C in cands
        sizes = sorted(len(b) for b in C)
        ok &= finest and len(set(sizes)) == 1
        if 1 < len(C) < 6: nprop += 1
        say(f"    A={A}: closure blocks {sorted(sorted(b) for b in C)}; finest invariant {finest}")
    check(ok, "closure = finest G-invariant equivalence, equal block sizes (blocks of imprimitivity)")
    check(nprop == 2, "A={0,3} and A={0,2} give proper systems (sizes 2 and 3); A={0,1} gives the universal block")


# ------------------------------------------------------------------ claim 3
def claim3():
    say("\n=== Claim 3: R34-base double")
    ks, reg = summary("R34-base", R34)
    rx, cv, pin = vertex_counts(R34)
    S, T = tuple(R34rec["marks"][0]), tuple(R34rec["marks"][1])
    check(len(R34) == 19 and is_prime(19) and (rx, cv, pin) == (15, 19, 0) and strictly_simple(R34),
          "area = degree 19 (prime), 15 reflex + 19 convex = 34 walls, strictly simple")
    check(set(reg) == {(2, 0), (6, 0), (4, 0), (8, -2)} and all(par(p) == (0, 0) for p in reg),
          "regular sites exactly (2,0),(6,0) interior and (4,0),(8,-2) smooth; all even-even")
    check(ks[S] == "interior" and ks[T] == "interior", f"marks {S},{T} interior")
    off_corner_only = all(ks[p] in ("reflex", "convex") for p in ks if par(p) != (0, 0))
    check(off_corner_only, "all three off-classes corner-only upstairs")
    ax, ninth, rel = local_count(R34, S, T)
    check(ax and ninth and rel == {(1, 1)}, f"claim-4 instance: 8 distinct axial reflexes, diagonal reflex(es) {ninth}")

    # parity lemma: integer reflections x -> 2c - x preserve parity, so unfolded T is even-even;
    # D = T' - S even, g = gcd >= 2, first primitive step S + D/g has an odd coordinate.
    lem = True
    for Dx in range(-12, 13, 2):
        for Dy in range(-12, 13, 2):
            if (Dx, Dy) == (0, 0): continue
            g = gcd(Dx, Dy); v = (Dx // g, Dy // g)
            lem &= g >= 2 and (v[0] % 2 or v[1] % 2) == 1
    check(lem, "for every nonzero even displacement in [-12,12]^2: gcd >= 2 and primitive step has odd coordinate")

    # bounded exact ray check from S (requested): primitive |p|,|q| <= 9, crossings <= 4*area.
    cap = 4 * len(R34)
    n = 0; first = 0; reach = 0; kinds = {"reflex": 0, "convex": 0}; parok = True
    for p in range(-9, 10):
        for q in range(-9, 10):
            if (p, q) == (0, 0) or gcd(abs(p), abs(q)) != 1: continue
            n += 1
            r1 = trace(R34, S, (p, q), 1)
            if not r1["ok"]:
                first += 1
                c = r1["corner"]; kinds[kind(R34, c)] = kinds.get(kind(R34, c), 0) + 1
                parok &= par(c) == ((S[0] + p) % 2, (S[1] + q) % 2) and par(c) != (0, 0)
            m = max(1, cap // (abs(p) + abs(q)))
            rm = trace(R34, S, (p, q), m)
            if rm["ok"] and rm["end"] in {(T[0], T[1]), (S[0], S[1])}: reach += 1
    say(f"    {n} primitive directions; first-step corner stops by kind {kinds}")
    check(first == n, "every ray from S stops at a corner at its first lattice point (primitive step 1)")
    check(parok, "stop corner parity = parity of S+v (fold preserves parity) and is not even-even")
    check(reach == 0, "no ray reaches T (or returns to S) within 4*area crossings")


# ------------------------------------------------------------------ claim 4 instances
def claim4():
    say("\n=== Claim 4 scope: R22 and P6 are NOT corner-only upstairs (only their N5 is)")
    for nm, c in (("R22", R22), ("P6", P6)):
        ks, reg = summary(nm, c)
        ints = [p for p in reg if ks[p] == "interior"]
        a = par(ints[0])
        offreg = sorted(p for p in reg if par(p) != a)
        check(len(ints) == 2 and par(ints[1]) == a and offreg,
              f"{nm}: interior marks {ints} in class {a}; off-class smooth sites upstairs {offreg} (branch does not apply)")
        ax, ninth, rel = local_count(c, ints[0], ints[1])
        check(not ax, f"{nm}: axial-neighbour step of the count fails, as expected outside the branch")


# ------------------------------------------------------------------ claim 5
def claim5():
    say("\n=== Claim 5: single proper factor table")
    rows = []
    for z in range(0, 9):
        for k in range(2, 9):
            if k * z > 8: continue
            for m in range(2, 40):
                q = 2 * m - 2 - 2 * z
                if 2 <= q <= m // 2: rows.append((k, z, m, k * m))
    say(f"    rows (k,z,m,area): {rows}")
    check([r[:3] for r in rows] == [(2, 2, 4), (3, 2, 4), (4, 2, 4), (2, 3, 5), (2, 4, 6)],
          "rows are exactly (2,2,4),(3,2,4),(4,2,4),(2,3,5),(2,4,6)")
    check(max(r[3] for r in rows) == 16 and all(2 * r[2] - 2 - 2 * r[1] == 2 for r in rows),
          "upstairs areas <= 16; q = 2 in every row")


# ------------------------------------------------------------------ claim 6
def claim6():
    say("\n=== Claim 6: N5 hand check (R22, P6)")
    ks, reg = summary("staircase P0", set(P0))
    zr, zc, _ = vertex_counts(set(P0))
    smooth = [p for p in reg if ks[p] == "smooth"]
    m = len(P0); z = zr; q = 2 * m - 2 - 2 * z
    check(m == 5 and z == 3 and q == 2 and len(smooth) == 2 and len(reg) == 2,
          f"N5 base: m=5, z=3, q = 2m-2-2z = {q} = number of regular sites {smooth}")
    check(par(smooth[0]) == par(smooth[1]), "both N5 regular sites in one class (off-classes corner-only in N5)")
    check(zc + 2 * q + 3 * z == 4 * m, f"fibre sum c1+2q+3z = {zc}+{2*q}+{3*z} = 4m")
    ksq, regq = summary("P6 tile Qp", Qp)
    zp = vertex_counts(Qp)[0]
    check(len(Qp) == 5 and zp == 3 and len(regq) == 2 and par(regq[0]) == par(regq[1]) == (1, 0),
          f"P6 tile Qp: 5-cell staircase, z=3, two regular sites {regq} in the P6 mark class (1,0)")
    for nm, c, k in (("R22", R22, 3), ("P6", P6, 4)):
        r = vertex_counts(c)[0]
        check(len(c) == 5 * k and k * 3 == r and strictly_simple(c), f"{nm}: area {len(c)} = 5k, k={k}, kz={3 * k} = r={r}")


