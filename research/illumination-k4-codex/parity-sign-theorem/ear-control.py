"""Exact axis-cone reduction and one-diagonal completion in the fixed room."""
from pathlib import Path
from fractions import Fraction as F
import json
import numpy as np
from scipy.optimize import linprog
ROOT=Path(__file__).resolve().parent
j=json.loads((ROOT/'coupling.json').read_text());W=j['walls'];dim=W+4
normals=list(map(tuple,j['offset_normals']));theta=tuple(map(F,j['offset_base_point']))
G=[tuple(map(F,e['offset_gradient'])) for e in j['events']]
dot=lambda a,b:sum(x*y for x,y in zip(a,b))
unit=lambda k:tuple(F(i==k) for i in range(dim))

def solve(A,b,unique=False):
    n=len(A[0]);M=[list(row)+[rhs] for row,rhs in zip(A,b)];piv=[];k=0
    for c in range(n):
        p=next((i for i in range(k,len(M)) if M[i][c]),None)
        if p is None:continue
        M[k],M[p]=M[p],M[k];v=M[k][c];M[k]=[x/v for x in M[k]]
        for i in range(len(M)):
            if i!=k and M[i][c]:v=M[i][c];M[i]=[x-v*y for x,y in zip(M[i],M[k])]
        piv.append(c);k+=1
        if k==len(M):break
    assert all(any(row[:n]) or not row[n] for row in M)
    if unique:assert len(piv)==n
    x=[F(0)]*n
    for i,c in enumerate(piv):x[c]=M[i][-1]
    assert all(dot(row,x)==rhs for row,rhs in zip(A,b))
    return tuple(x),len(piv)

def rank(rows):return solve(list(zip(*rows)),[F(0)]*dim)[1]

eta=[F(0)]*dim;eta[5]=F(2);eta[6]=F(-1);eta=tuple(eta)
axis=[i for i,e in enumerate(j['events']) if any(sorted(abs(e['corner'][k]-p[k]) for k in (0,1))==[0,1] for p in j['room']['marked'])]
vals=[dot(row,eta) for row in G]
assert all(vals[i]>=0 for i in axis)
Z=[i for i in axis if vals[i]==0];P=[i for i in axis if vals[i]>0]
assert len(Z)==94 and len(P)==8
scales=[max(map(abs,G[i])) for i in Z]
R=[tuple(v/s for v in G[i]) for i,s in zip(Z,scales)]
M=np.array([[float(v) for v in row] for row in R])
lp=linprog(np.ones(len(R)),A_eq=M.T,b_eq=np.zeros(dim),bounds=[(1,None)]*len(R),method='highs')
assert lp.success
# Exact recovery of LP weights: keep bounds at1, solve for remaining variables.
active=[i for i,v in enumerate(lp.x) if abs(v-1)<1e-8];free=[i for i in range(len(R)) if i not in active]
A=[[R[i][c] for i in free] for c in range(dim)]
b=[-sum(R[i][c] for i in active) for c in range(dim)]
solution,_=solve(A,b,unique=True)
mu=[F(1)]*len(R)
for i,v in zip(free,solution):mu[i]=v
assert all(v>=1 for v in mu)
weights=[v/s for v,s in zip(mu,scales)]
assert all(sum(a*G[i][c] for i,a in zip(Z,weights))==0 for c in range(dim))
assert rank([G[i] for i in Z])==25
# Prove the four-dimensional zero-row kernel is exactly translations, scale, ear.
trans=[tuple(F(n[a]) for n in normals)+tuple(F(k%2==a) for k in range(4)) for a in (0,1)]
assert rank(trans+[theta,eta])==4
assert all(dot(G[i],v)==0 for i in Z for v in trans+[theta,eta])
# Thus all feasible axis motions lie in symmetries + a*eta. The8other rows force a>=0.
a=P[0];d=50
assert j['events'][d]['corner']==[1,3] and vals[d]==-2
assert vals[a]>0
# A positive combination of one positive-axis and one negative-diagonal row
# annihilates eta; absorb the resulting span vector with the positive zero stress.
alpha=-vals[d];beta=vals[a]
H=[alpha*G[a][c]+beta*G[d][c] for c in range(dim)]
coef,_=solve([[G[i][c] for i in Z] for c in range(dim)],[-v for v in H])
C=1+max([F(0)]+[-v/w for v,w in zip(coef,weights)])
completed=[v+C*w for v,w in zip(coef,weights)]
assert all(v>0 for v in completed)
indices=Z+[a,d];lambdas=completed+[alpha,beta]
assert len(indices)==len(set(indices))==96
assert rank([G[i] for i in indices])==26
assert all(sum(l*G[i][c] for i,l in zip(indices,lambdas))==0 for c in range(dim))
# Verify the physical motion is only the three vertices of the triangular ear.
vertex_delta=[]
for c in range(W):
    p=(c-1)%W;n=normals[p];m=normals[c];det=n[0]*m[1]-n[1]*m[0]
    vertex_delta.append(((eta[p]*m[1]-n[1]*eta[c])/det,(n[0]*eta[c]-eta[p]*m[0])/det))
assert {i:v for i,v in enumerate(vertex_delta) if v!=(0,0)}=={5:(0,2),6:(-1,1),7:(0,1)}
# Bind this simple mode to the earlier normalized dual control modulo scale.
dual=tuple(map(F,json.loads((ROOT/'dual-control.json').read_text())['offset_deformation']))
scale_about_source=tuple(theta[c]-sum(F(j['room']['marked'][0][k])*trans[k][c] for k in (0,1)) for c in range(dim))
assert eta==tuple(2*dual[c]-scale_about_source[c]/26 for c in range(dim))
out={'status':'EXACT_PASS','tag':j['tag'],
     'ear_offset_deformation':list(map(str,eta)),
     'ear_vertex_deformations':{str(i):list(map(str,v)) for i,v in enumerate(vertex_delta) if v!=(0,0)},
     'zero_axis_rows':Z,'zero_axis_rank':25,'strict_positive_zero_stress':list(map(str,weights)),
     'positive_axis_rows':P,'positive_axis_values':[str(vals[i]) for i in P],
     'axis_cone_modulo_symmetries':'exactly the nonnegative ray generated by eta, for the saved102axis rows',
     'diagonal_cut_event':{'index':d,'direction':j['events'][d]['direction'],'corner':[1,3],'eta_value':str(vals[d])},
     'completed_certificate_indices':indices,'completed_certificate_weights':list(map(str,lambdas)),
     'completed_exact_rank':26,'completed_rows':96,
     'scope':'Exact finite certificate and geometric ear interpretation for ONE fixed room and SAVED events. No claim that every parity room has this cone structure.'}
(ROOT/'ear-control.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps({k:v for k,v in out.items() if k not in ('ear_offset_deformation','zero_axis_rows','strict_positive_zero_stress','completed_certificate_indices','completed_certificate_weights')},indent=2))
